"""
Общая заглушка сетки лица.

mediapipe в тестах не запускается: он медленный, требует настоящего лица в
кадре и проверяет совсем не то, что нам нужно. Модулю маски достаточно списка
из 468 точек, и заглушка отдаёт именно его.
"""

import numpy as np
import pytest

from app.pipelines import hair_mask, head_mask

# Канонические смещения относительно центра лица, до масштаба и поворота.
# Высота лица (подбородок → переносица) равна 80, ширина (глаз → глаз, ×2) — 120.
_OFFSETS = {
    152: (0, 60),  # подбородок
    9: (0, -20),  # переносица, она же верх «оси лица»
    # Макушка лба: по ней и кончику носа меряется наклон головы
    # (`head_mask.head_pose`). Смещение выбрано не на глаз — при нём отношение
    # «лоб→нос» к «нос→подбородок» даёт 0.18, то есть ровно тот базовый
    # уровень, который замерен на живых фронтальных кадрах. Без этой точки
    # заглушка отдавала бы её в центре лица, и фас читался бы как наклон в 40°
    10: (0, -42),
    33: (-30, -10),
    133: (-12, -10),  # правый глаз: внешний и внутренний углы
    362: (12, -10),
    263: (30, -10),  # левый глаз
    234: (-50, 0),
    454: (50, 0),  # скулы на уровне ушей
    168: (0, -14),
    6: (0, -6),
    195: (0, 2),
    4: (0, 12),
    1: (0, 18),  # спинка носа
    98: (-10, 22),
    327: (10, 22),  # крылья носа
    61: (-18, 38),
    291: (18, 38),  # углы рта
    70: (-34, -24),
    300: (34, -24),  # внешние края бровей
}


# Глубина заглушки: насколько скула уходит НАЗАД от кончика носа, в тех же
# единицах, что и смещения выше. Ровно полуширина лица — так на живом лице и
# выходит: дальняя щека схлопывается около 43-45°, то есть там, где
# `полуширина * cos = глубина * sin`. Меньше этого числа профиль наступал бы
# позже, чем в жизни, и отсечение проверялось бы не на том угле.
_DEPTH = 50.0

# Полувысота глаза в тех же единицах: угол глаза — точка, а веко имеет высоту
_EYE_HALF_HEIGHT = 5.0


def face_mesh(centre=(200, 200), scale=1.0, angle=0.0, yaw=0.0) -> list[tuple[int, int]]:
    """
    468 точек-заглушек: лицо в заданном месте, размере, наклоне и повороте.

    :param centre: куда поставить центр лица
    :param scale: множитель размера (1.0 — высота лица 80 пикселей)
    :param angle: наклон головы набок в градусах (поворот в плоскости кадра)
    :param yaw: поворот головы вокруг вертикали в градусах — то, что делает
        сетку АСИММЕТРИЧНОЙ. Лицо выпуклое, и точки у краёв лежат глубже
        середины; поворот подмешивает эту глубину в поперечную координату, из-за
        чего одна щека в проекции растягивается, а вторая сжимается и на 45°
        схлопывается совсем. Ради этого параметр и заведён: симметричной сеткой
        поворот головы не проверяется никак
    """
    radians = np.radians(angle)
    rotation = np.array([[np.cos(radians), -np.sin(radians)], [np.sin(radians), np.cos(radians)]])
    turn = np.radians(yaw)

    def place(dx: float, dy: float) -> tuple[int, int]:
        # Параболическая глубина: середина лица у камеры, края отступают назад.
        # Грубо, но именно эта грубость и создаёт правильную проекционную
        # асимметрию — точную форму черепа здесь проверять нечем
        depth = -((dx / 50.0) ** 2) * _DEPTH
        turned = dx * np.cos(turn) + depth * np.sin(turn)
        x, y = rotation @ (np.array([turned, dy], dtype=np.float64) * scale)
        return int(round(centre[0] + x)), int(round(centre[1] + y))

    points = [place(0, 0)] * 468
    for index, (dx, dy) in _OFFSETS.items():
        points[index] = place(dx, dy)

    # Дуга челюсти — полуокружность от скулы через подбородок ко второй скуле.
    #
    # Знак косинуса задаёт, с какой стороны кадра окажется каждая скула, и он не
    # произволен: дуга начинается с 454, а в настоящей сетке 454 лежит на одной
    # стороне с внешним углом глаза 263, тогда как 234 — с углом 33. Проверено
    # на живом кадре. С обратным знаком заглушка зеркалила овал относительно
    # собственных глаз, и всякий, кто вздумает связать скулу с глазом её
    # стороны, получил бы пару с разных половин лица
    for offset, index in enumerate(head_mask._JAW_ARC):
        step = np.pi * offset / (len(head_mask._JAW_ARC) - 1)
        points[index] = place(50 * np.cos(step), 60 * np.sin(step))

    # Линия бровей
    for offset, index in enumerate(head_mask._BROW_ARC):
        share = offset / (len(head_mask._BROW_ARC) - 1)
        points[index] = place(-34 + 68 * share, -22)

    # Контуры глаз — по эллипсу между углами, которые уже заданы в _OFFSETS.
    #
    # Без этого двенадцать из шестнадцати точек кольца оставались в центре лица,
    # и выпуклая оболочка глаза (`hair_mask._eye_guard`) растягивалась на обе
    # глазницы вместе с переносицей. Тесты при этом проходили — полигон накрывал
    # всё, что от него требовали, — но проверяли выдумку.
    #
    # Порядок колец канонический: нулевая точка каждого лежит в одном углу,
    # восьмая — в противоположном, поэтому `cos` разводит их ровно по тем
    # координатам, что стоят в _OFFSETS.
    for ring in (hair_mask._EYE_RING_A, hair_mask._EYE_RING_B):
        first, ninth = points[ring[0]], points[ring[8]]
        centre_x = (first[0] + ninth[0]) / 2.0
        centre_y = (first[1] + ninth[1]) / 2.0
        half_width = abs(first[0] - ninth[0]) / 2.0
        for offset, index in enumerate(ring):
            angle = np.pi * offset / 8.0
            points[index] = (
                int(round(centre_x - half_width * np.cos(angle))),
                int(round(centre_y + _EYE_HALF_HEIGHT * scale * np.sin(angle))),
            )

    return points


@pytest.fixture
def mesh():
    """Фабрика сеток — тесты сами решают, где и какого размера лицо."""
    return face_mesh
