"""
Стирание старой причёски В КАДРЕ, который уезжает редактору.

**Путь провалился и по умолчанию выключен (`erase_ratio=0`).** Оставлен
переключателем по той же причине, по какой оставлены `kontext_multi` и
`identity_inpaint`: воспроизвести провал одной переменной окружения дешевле,
чем спорить о нём. Что показал живой прогон, читать ниже, после описания
гипотезы, — порядок здесь важнее краткости.

Гипотеза. Маска волос дошла до состояния, когда её геометрия уже не виновата:
`hair_left_px` считает единицы пикселей, прядь на щеке лежит внутри полностью
открытой области — и всё равно возвращается из ответа редактора на том же месте.
Это не промах маски и не слабость промпта: инструкция велит стереть локон
отдельным предложением, а редактор его сохраняет.

Причина в том, как устроены эти модели. Универсальный редактор не рисует область
с нуля — он ПЕРЕПИСЫВАЕТ присланные пиксели, и всё, что похоже на осмысленную
структуру, для него данные, а не мусор. Тёмная прядь на светлой щеке — это
контрастная вытянутая линия ровно там, где у человека проходит тень от скулы или
край челюсти. Модель читает её как часть анатомии лица, а лицо ей запрещено
трогать тем же промптом. Слова против пикселей проигрывают: текст задаёт
намерение, а вход задаёт факты.

Отсюда единственный оставшийся рычаг — **факты**. Пиксели старой причёски
разрушаются до отправки: там, где маска открыта, структуры не остаётся вовсе, и
сохранять редактору становится нечего. Это не «подсказка» и не «улучшение
входа» — это ровно то, что мы и просим сделать: маска открыта там, где старых
волос быть не должно.

Как именно. Двумя действиями, и оба нужны.

  1. **Заливка по окружению** (`cv2.inpaint`). Одного размытия мало: размытая
     тёмная прядь остаётся тёмным пятном, и модель дорисует по нему тёмные
     волосы — то есть ровно то, что мы удаляли. Заливка же тянет цвет из-за
     ГРАНИЦЫ маски, где лежит настоящее окружение: небо, кожа, воротник. После
     неё в области нет ни тёмного, ни светлого — там продолжение сцены.
  2. **Размытие поверх заливки.** Telea оставляет за собой радиальные штрихи от
     границы внутрь — своя структура, слабее исходной, но структура. Размытие
     убирает и её. Детали здесь не нужны и вредны: чем ровнее пятно, тем меньше
     редактору есть что «сохранить».

Считается это на уменьшенной копии, и не только ради скорости. Инпейнт на 4K —
секунды и радиальные штрихи в полный рост; на рабочей стороне в полтысячи
пикселей он занимает миллисекунды, а обратное растяжение само по себе
дополнительно сглаживает результат. Точность здесь не нужна ни в каком виде:
итог этой работы — заведомо неправильные пиксели, задача которых лишь не
подсказывать модели ничего.

**Что показал прогон.** Гипотеза оказалась неверной, и опровергла её эта же
работа — тем, что провела чистый эксперимент. Стирание залило мылом ВСЮ открытую
область, а прядь на щеке осталась резкой и нетронутой. Вывод из этого
однозначный: под маской её не было вовсе. Разметка не относит такой локон ни к
волосам, ни к лицу, и `hair_left_px` про него молчал не потому, что остатка нет,
а потому, что меряет остаток КЛАССА волос. Дотягивается до него не стирание, а
геометрия — полоса вдоль щеки, `hair_mask._cheek_bands`.

Заодно выяснилась цена, и она высока. Вместе со структурой пропадает силуэт
старой копны, а он был для редактора единственным указанием, где вообще растут
волосы: получив ровное пятно, nano-banana нарисовал ёжик прямо по черепу, и
голова вышла лысой. И границы заливки вернули тот самый светлый ореол — заливка
тянет цвет с краёв внутрь, редактор повторяет её тон, а лежит он внутри маски,
то есть переживает вклейку. Оба дефекта — плата за приём, который своей задачи
не решил; включать его поверх работающей полосы незачем.

**Чего этот модуль не делает.** Его результат не попадает в готовый разворот
никогда. Стёртая копия существует ровно до загрузки в CDN; обратно в шаблон
вклеивается ответ редактора, а вклеивается он в ИСХОДНЫЙ кадр (`composite.paste`
получает нетронутый `scene`). Поэтому вне маски здесь не меняется ни один
пиксель, а внутри — не имеет значения, насколько правдоподобно вышло: если
редактор промолчит и вернёт присланное, это поймает проверка `changed`, которая
сравнивает ответ с тем, что ОТПРАВЛЯЛИ, а не с шаблоном.
"""

from __future__ import annotations

from typing import Any

from app.core.logging import get_logger

log = get_logger(__name__)

# Рабочая сторона уменьшенной копии, пиксели. На ней считаются и заливка, и
# размытие, и метрика структуры. Число некритично: результат — мягкое пятно,
# и разница между 512 и 1024 в нём не видна, а инпейнт дорожает квадратично.
_WORK_PX = 512

# Радиус, в котором Telea ищет опорные пиксели, — в масштабе уменьшенной копии.
# Больше делать незачем: границу заливки всё равно накрывает размытие.
_INPAINT_RADIUS = 3

# Сколько пикселей должно остаться ВНЕ маски, чтобы заливке было откуда брать
# цвет. Маска, накрывшая окно целиком, вернула бы из inpaint чёрное поле — то
# есть структуру мощнее исходной, да ещё и с ложной подсказкой «тут темно».
_MIN_OUTSIDE_PX = 64


def _structure(gray: Any, inside: Any) -> float:
    """
    Сколько структуры в области: средний модуль лапласиана, уровни 0..255.

    Ради ответа на единственный вопрос — сработало ли стирание. Число уезжает в
    мету до и после, и падение на порядок означает, что сохранять редактору в
    этой области больше нечего. Осталось прежним — значит, размытие слабое для
    этого кадра, и крутить надо `ML_HAIR_ERASE_RATIO`.
    """
    import cv2
    import numpy as np

    if not inside.any():
        return 0.0

    return float(np.abs(cv2.Laplacian(gray, cv2.CV_32F))[inside].mean())


def wipe(image: Any, mask: Any, face_height: float, blur_ratio: float) -> tuple[Any, dict]:
    """
    Копия кадра, в которой под маской не осталось структуры старых волос.

    :param image: кадр (окно вокруг головы), BGR numpy.ndarray
    :param mask: маска волос того же размера, uint8. Стирается всё, где она
        больше нуля, — включая растушёванный хвост: только так заливка берёт
        цвет из пикселей, лежащих ЗА всей маской
    :param face_height: высота лица персонажа в пикселях, база долей
    :param blur_ratio: радиус размытия заливки, доля высоты лица. 0 выключает
        стирание целиком, и тогда возвращается тот же объект — редактору уезжает
        исходный кадр, как было до этого модуля
    :return: кадр и отчёт. `erased=False` означает «кадр не тронут», и причина
        рядом: стирание выключено, маска пуста или заливке не из чего брать цвет
    """
    import cv2
    import numpy as np

    if blur_ratio <= 0:
        return image, {"erased": False, "reason": "off"}

    if mask.ndim == 3:
        mask = mask[..., 0]

    region = (mask > 0).astype(np.uint8)
    if not region.any():
        return image, {"erased": False, "reason": "empty"}

    height, width = image.shape[:2]
    scale = min(1.0, _WORK_PX / float(max(height, width)))
    size = (max(1, int(round(width * scale))), max(1, int(round(height * scale))))

    if scale < 1.0:
        small = cv2.resize(image, size, interpolation=cv2.INTER_AREA)
        # INTER_AREA плюс «любое попадание» вместо ближайшего соседа: на
        # уменьшении тонкая прядь шириной в пиксель иначе просто исчезает из
        # области — и остаётся в кадре нестёртой, то есть ровно тем, из-за чего
        # всё это написано
        small_region = (cv2.resize(region * 255, size, interpolation=cv2.INTER_AREA) > 0).astype(
            np.uint8
        )
    else:
        small, small_region = image, region

    outside_px = int(np.count_nonzero(small_region == 0))
    if outside_px < _MIN_OUTSIDE_PX:
        # Заливке неоткуда брать цвет: inpaint вернул бы чёрное поле, а это
        # худшая из возможных подсказок — «здесь темно». Честнее не трогать
        log.warning(
            "старая причёска не стёрта: маска накрыла окно почти целиком",
            extra={"outside_px": outside_px, "floor": _MIN_OUTSIDE_PX},
        )
        return image, {"erased": False, "reason": "no_context"}

    gray = cv2.cvtColor(small, cv2.COLOR_BGR2GRAY)
    inside = small_region > 0
    before = _structure(gray, inside)

    filled = cv2.inpaint(small, small_region, _INPAINT_RADIUS, cv2.INPAINT_TELEA)

    # Сигма — в масштабе уменьшенной копии. Ядро OpenCV считает сам: задавать
    # его руками значит промахнуться мимо собственной сигмы
    sigma = face_height * blur_ratio * scale
    if sigma >= 0.5:
        filled = cv2.GaussianBlur(filled, (0, 0), sigma)

    after = _structure(cv2.cvtColor(filled, cv2.COLOR_BGR2GRAY), inside)

    if scale < 1.0:
        filled = cv2.resize(filled, (width, height), interpolation=cv2.INTER_LINEAR)

    # Вес — сама маска, вместе с растушёвкой. Резкий край стирания стал бы новой
    # структурой по контуру маски, а это то же самое, от чего мы уходим
    alpha = (mask.astype(np.float32) / 255.0)[..., None]
    erased = np.rint(image.astype(np.float32) * (1.0 - alpha) + filled.astype(np.float32) * alpha)
    erased = erased.astype(np.uint8)

    # Обещание «вне маски не тронуто» держится не на округлении арифметики
    untouched = mask == 0
    erased[untouched] = image[untouched]

    meta = {
        "erased": True,
        "blur_ratio": blur_ratio,
        "blur_px": round(float(face_height * blur_ratio), 1),
        "work_scale": round(scale, 3),
        # Сколько структуры было под маской и сколько осталось, уровни 0..255.
        # Упало на порядок — сохранять редактору нечего; осталось прежним —
        # размытие слабо для этого кадра
        "structure_before": round(before, 2),
        "structure_after": round(after, 2),
        "erased_px": int(np.count_nonzero(mask > 127)),
    }
    log.info("старая причёска стёрта до отправки редактору", extra=meta)
    return erased, meta
