"""
Маска **одних только волос** персонажа на шаблоне.

Зачем понадобилась вторая маска. Фейссвоп переносит лицо и ничего кроме лица:
причёска остаётся от шаблона. Донору с коротким светлым ёжиком достаётся чужая
грива, и починить это внутри фейссвопа нечем — он не читает текста и волос не
касается вовсе. Значит, причёску надо править отдельным проходом, а править её
отдельным проходом можно только по отдельной области.

Область эта устроена наоборот к `head_mask.py`. Там маска накрывает голову
целиком (лицо, волосы, шею) — потому что голова рисуется заново. Здесь лицо
защищается: **всё, что отличает донора, приезжает фейссвопом, и правка волос
обязана оставить лицо нетронутым до пикселя**. Причин две, и обе жёсткие:

  * фейссвоп идёт ВТОРЫМ и ищет лицо на уже поправленном шаблоне своим
    детектором. Тронутые диффузией глаза, нос и рот — это риск того самого
    молчаливого отказа, ради отлова которого написана проверка `changed`;
  * лицо на шаблоне — фотореалистичное. Любая диффузия по нему возвращает
    сглаженную кожу, то есть ровно то, что запрещено правилом серии.

Правило области:

    маска = (HAIR своего персонажа ∪ кожа лба выше линии бровей)
            расширенный, растушёванный
            минус  (FACE ∪ контур лица из сетки, кроме волос), ниже той же линии,
                   но НЕ там, где лежат волосы,
            плюс   ядро лица (глаза, нос, рот) — оно не отдаётся никогда

Оговорка про «не там, где лежат волосы» — не деталь, а третье выстраданное
правило. Защита расширяется наружу, в прилегающие волосы, и спасала от правки
чёлку на лбу и бакенбарды на щеках: редактор их не стирал, фейссвоп вклеивал
лицо ПОД них, и с висков готового разворота свисали тёмные ошмётки прежнего
героя. Волосы важнее защиты — кроме ядра лица, иначе разметка, принявшая
затенённое лицо за волосы, пустила бы диффузию по глазам.

Про лоб — отдельно, потому что это правка после третьего прогона. Пока лоб был
защищён целиком, нижняя граница маски проходила по открытой коже; вклейка
геометрию не выравнивает, и сдвинувшаяся на несколько пикселей генерация
превращала эту границу в рубец — голова читалась как накладка. Опущенная до
бровей маска отдаёт редактору лоб целиком, полосы старой кожи между лицом от
фейссвопа и новой причёской не остаётся, а сам стык уходит в брови, где его
накрывает своей растушёвкой фейссвоп. Управляет этим `forehead_ratio`.

Что здесь важно и неочевидно.

**Берётся след СТАРЫХ волос целиком.** Длинные волосы лежат на плечах, закрывают
уши, шею и часть одежды. Короткая стрижка их не закрывает — значит, на их месте
модель обязана дорисовать то, что под ними было: фон, ухо, шею, ткань. Обойти
это никакой аккуратностью маски нельзя: нельзя убрать длинные волосы, не
перерисовав того, что они прятали. Поэтому одежда под волосами в маску входит —
и только она; ткань, которой волосы не касались, остаётся вне области. Сколько
её задето, считается и уезжает в мету.

**Чёлку защита не трогает.** Вычитается не весь контур лица, а контур МИНУС
класс волос: прядь, упавшая на бровь, — это волосы, и перерисовываться она
обязана вместе с остальной причёской. Кожа лица под тем же контуром остаётся
защищённой.

**Полоса вдоль щёк — область, объявленная волосами без разметки.** Всё описанное
выше исходит из того, что причёску показывает сегментатор: маска строится из
класса HAIR, а защита — из класса FACE. Прогон, стоивший этой правки, показал
третий случай, который в эту картину не укладывается вовсе: локон от виска к
щеке и дальше к воротнику не размечен НИКАК — ни волосами, ни лицом. Для
сегментатора (он работает на 256x256) его там просто нет, и `hair_left_px`
такую прядь не считает по построению — он меряет остаток КЛАССА волос, а класс
её не знает. Доказано это стиранием: залитая мылом маска оставила локон резким,
то есть он лежал вне маски целиком.

Из этого следует, что ни одно число, работающее с разметкой, до него не
дотянется — ни `dilate` (расширять нечего, источника нет), ни `guard` (он
отпускает защиту, а не добавляет область), ни `core`. Нужен источник, который
разметки не спрашивает вовсе: `cheek_ratio` кладёт по обе стороны от оси лица
полосу — от виска вниз мимо челюсти к воротнику — и объявляет её причёской по
факту своего существования.

Полоса живёт в осях головы, а не кадра, поэтому наклон головы её поворачивает
вместе с лицом. Внутрь она не заходит: её ближняя граница отстоит от оси на
`_CHEEK_INNER` полуширины лица, то есть проходит снаружи от внешних углов глаз.
Гарантию даёт не это расстояние, а ядро лица — оно накладывается поверх всего и
глаза, нос и рот не отдаёт ни при каком значении.

Защиту полоса гасит наравне с настоящими волосами (через `hair_soft`), и это
существенно: иначе класс FACE, растянутый на всю щёку, вычел бы её обратно —
защита отнимается ПОСЛЕ дилатации, и на щеке маска умножилась бы на ноль. То
есть полоса, не гасящая защиту, не работала бы вовсе.

Без разметки (веса необязательны) работает запасной путь: кольцо «эллипс головы
минус лицо». Он не знает ни длины волос, ни их формы, поэтому берёт с запасом и
годится только как затычка — в логе он виден предупреждением.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from app.core.errors import InvalidImageError, NoFaceDetectedError
from app.core.logging import get_logger
from app.pipelines import head_mask, parsing

log = get_logger(__name__)

# Смыкание разрывов класса волос, доля меньшей стороны кадра. То же число и по
# той же причине, что в head_mask: класс HAIR рвётся на пряди, и компонента
# причёски теряет связь с головой на первом же просвете.
_CLOSE_RATIO = 0.004

# Точки, по которым строится ядро лица: углы обоих глаз, спинка носа и углы рта.
# Всё, что нужно детектору фейссвопа, и ничего сверх того — виски и скулы сюда
# не входят намеренно, оттуда как раз и выжигаются остатки старой причёски.
_CORE = (33, 133, 362, 263, 1, 4, 61, 291)

# Запасной путь: во что превращается «область волос», когда разметки нет. Доли
# те же, что у эллипса головы, только лицо из него вычитается.
_ELLIPSE_FACE_MARGIN = 0.06

# Геометрия полосы вдоль щеки, доли ПОЛУШИРИНЫ лица (face_width / 2, то есть
# расстояния от оси до скулы у уха). В долях, а не в пикселях, по той же причине,
# что и всё остальное здесь: одно число обязано работать и на превью, и на 4K.
#
# Ближняя граница снаружи от внешних углов глаз — их лицо шире не бывает, а
# уходить внутрь полосе незачем: локон висит на щеке, а не на носу. Дальняя
# уводит полосу за ухо, где длинная прядь и заканчивается; дальше начинается
# плечо соседа по развороту, и нам туда не надо.
_CHEEK_INNER, _CHEEK_OUTER = 0.75, 1.8

# Докуда полоса поднимается вверх, доли высоты лица над подбородком. Чуть выше
# линии бровей (она ровно на 1.0): локон начинается на виске, и полоса обязана
# сомкнуться с классом волос, а не оставить между собой и им разрыв.
_CHEEK_TOP = 1.15

# Какая доля старых волос может остаться вне маски, прежде чем это стоит строки
# в логе. Ноль недостижим: ядро лица не отдаёт прядь, упавшую на глаз, — но это
# единицы пикселей, а проценты означают спасённую защитой чёлку.
_LEFT_WARN_SHARE = 0.02


@dataclass
class HairMask:
    """
    Область причёски и всё, что о ней известно.

    :param mask: одноканальная маска uint8 размера кадра
    :param face_height: высота лица персонажа в пикселях — база всех долей
    :param meta: уезжает в X-Swap-Meta. Когда причёска вышла не той или поехала
        одежда, смотрят сюда: чем построена область и сколько ткани задето
    """

    mask: Any
    face_height: float
    meta: dict = field(default_factory=dict)


def _seed(shape: tuple[int, int], points: list[tuple[int, int]] | None, fallback: Any) -> Any:
    """
    Затравка «это наш персонаж»: залитый контур лица либо пятно из разметки.

    Нужна ровно за тем же, зачем в head_mask: на развороте героев несколько, а
    классы разметки приходят одним слоем на всех сразу. Перекрашивать причёску
    соседа мы не нанимались.
    """
    import cv2
    import numpy as np

    if points is None:
        return fallback

    seed = np.zeros(shape, dtype=np.uint8)
    cv2.fillPoly(seed, [head_mask.face_polygon(points)], 1)
    return seed


def _own_hair(parsed: parsing.Parsed, seed: Any, close: int) -> Any | None:
    """
    Класс волос, отобранный по принадлежности нашему персонажу. 0/255 либо None.

    Компонента ищется не по волосам, а по голове целиком (волосы ∪ лицо): сами
    по себе волосы затравку-лицо не пересекают — классы не перекрываются, — и
    поиск компоненты по ним отдал бы пустоту. Голова же связна, и, найдя её,
    пересечь с классом волос уже тривиально.
    """
    import cv2
    import numpy as np

    hair = (np.asarray(parsed.hair) > 127).astype(np.uint8)
    if not hair.any():
        return None

    face = (np.asarray(parsed.face) > 127).astype(np.uint8)
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * close + 1,) * 2)
    head = cv2.morphologyEx(np.maximum(hair, face), cv2.MORPH_CLOSE, kernel)

    own = head_mask.component_of(head, seed) if seed is not None else None
    if own is None:
        log.info("причёска не опознана затравкой — берём класс волос целиком")
        own = head

    region = np.minimum(own, hair)
    return None if not region.any() else region * 255


def _fallback_ring(shape: tuple[int, int], geometry: dict, points: list | None) -> Any | None:
    """
    Запасной путь: эллипс головы минус лицо. Разметки нет — формы волос тоже.

    Заведомо грубо: кольцо не знает ни длины причёски, ни того, где она
    кончается, и на длинные волосы попросту не дотянется. Годится, чтобы
    сервис не отказывал заказу целиком, но результат такой правки надо смотреть
    глазами — отсюда предупреждение в логе.
    """
    import cv2
    import numpy as np

    if points is None:
        return None

    ring = head_mask.head_ellipse(shape, geometry)
    face = np.zeros(shape, dtype=np.uint8)
    cv2.fillPoly(face, [head_mask.face_polygon(points)], 255)

    margin = max(1, int(round(geometry["face_height"] * _ELLIPSE_FACE_MARGIN)))
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * margin + 1,) * 2)
    ring = np.where(cv2.dilate(face, kernel) > 0, 0, ring).astype(np.uint8)

    return None if not ring.any() else ring


def _cheek_bands(shape: tuple[int, int], geometry: dict, cheek_ratio: float) -> Any | None:
    """
    Две полосы вдоль щёк: от виска вниз мимо челюсти к воротнику. 0/255 либо None.

    Единственное место в модуле, где область берётся НЕ из разметки. Написано
    против локона, которого сегментатор не видит вовсе: он не отнесён ни к
    волосам, ни к лицу, и потому недостижим ничем из остальных чисел. `dilate`
    расширяет источник, которого здесь нет; `guard` и `core` только отпускают
    защиту, а не добавляют область. Значит, область надо задать руками — по
    геометрии лица, а не по мнению модели о том, что на этих пикселях нарисовано.

    Прямоугольник на сторону, в осях головы: вдоль оси — от `_CHEEK_TOP` высот
    лица над подбородком (чуть выше бровей, чтобы сомкнуться с классом волос на
    виске) вниз до `cheek_ratio` высот НИЖЕ подбородка; поперёк — от
    `_CHEEK_INNER` до `_CHEEK_OUTER` полуширин лица.

    В осях головы, а не кадра, и по той же причине, что у среза лба и сужения
    защиты: у персонажа, склонившего голову набок, вертикальные полосы прошли бы
    по щеке с одной стороны и по фону с другой.

    Полуширина берётся из `face_width` — расстояния между скулами на уровне ушей,
    — потому что от него и отмеряются обе границы: «снаружи от глаз» и «за ухом».

    :param cheek_ratio: докуда полоса спускается ниже подбородка, доли высоты
        лица. 0 — полосы нет, и модуль работает ровно по разметке, как раньше
    """
    import cv2
    import numpy as np

    if cheek_ratio <= 0:
        return None

    chin, up, side = geometry["chin"], geometry["up"], geometry["side"]
    face_height = geometry["face_height"]
    half = max(1.0, float(geometry["face_width"]) / 2.0)

    top = face_height * _CHEEK_TOP
    bottom = -face_height * cheek_ratio
    inner, outer = half * _CHEEK_INNER, half * _CHEEK_OUTER

    bands = np.zeros(shape, dtype=np.uint8)
    for direction in (1.0, -1.0):
        cv2.fillConvexPoly(
            bands,
            np.array(
                [
                    chin + up * top + side * (direction * inner),
                    chin + up * top + side * (direction * outer),
                    chin + up * bottom + side * (direction * outer),
                    chin + up * bottom + side * (direction * inner),
                ],
                dtype=np.int32,
            ),
            255,
        )
    return bands


def _above_brows(shape: tuple[int, int], geometry: dict, forehead_ratio: float) -> Any:
    """
    Полуплоскость выше линии, отстоящей от бровей на `forehead_ratio` высот лица.

    Отвечает на вопрос «докуда маске можно спуститься по лбу». Линия строится
    перпендикулярно оси головы, то есть вместе с её наклоном: у персонажа,
    склонившего голову набок, горизонтальный срез прошёл бы через бровь с одной
    стороны и через волосы с другой.

    Брови лежат на расстоянии ровно одной высоты лица от подбородка — так эта
    высота и определена (`head_mask.face_geometry`), поэтому множитель
    `1 + forehead_ratio` и означает «на столько выше бровей».
    """
    import cv2
    import numpy as np

    chin, up, side = geometry["chin"], geometry["up"], geometry["side"]
    line = chin + up * (geometry["face_height"] * (1.0 + forehead_ratio))

    # Четырёхугольник, заведомо перекрывающий кадр в обе стороны: диагональ
    # гарантирует, что при любом наклоне оси его углы окажутся снаружи
    reach = float(shape[0] + shape[1])
    above = np.zeros(shape, dtype=np.uint8)
    cv2.fillConvexPoly(
        above,
        np.array(
            [
                line + side * reach,
                line - side * reach,
                line - side * reach + up * reach,
                line + side * reach + up * reach,
            ],
            dtype=np.int32,
        ),
        255,
    )
    return above


def _face_core(
    shape: tuple[int, int],
    points: list,
    margin: int,
    geometry: dict,
    core_ratio: float,
) -> Any:
    """
    Ядро лица: то, что не отдаётся редактору ни при каких условиях.

    Выпуклая оболочка глаз, носа и рта — ровно то, по чему детектор фейссвопа
    ищет лицо на поправленном шаблоне. Волосы её не перебивают, и это
    единственное исключение из правила «волосы важнее защиты»: прядь, оставшуюся
    поверх глаза, потерять не жалко, а перерисованный диффузией глаз — это и
    сглаженная кожа, и молчаливый отказ фейссвопа.

    Контур лица целиком на эту роль не годится: под него попадают виски и скулы,
    то есть ровно те места, откуда ошмётки старой причёски и надо выжигать.

    `core_ratio` сжимает оболочку ПОПЕРЁК оси лица — к средней линии, идущей от
    подбородка к бровям. Понадобилось это ради пряди, спускавшейся от виска к
    щеке: оболочка кончается на внешнем углу глаза, но дилатация уводит её ещё
    на `margin` в сторону виска, и локон оказывался под защитой.

    Сжатие безопасно не по осторожности значения, а по устройству: дилатация
    осталась круговой и возвращает накрытие обратно наружу. Пока сдвиг угла
    глаза (доля `1 - core_ratio` от полуширины лица) меньше `margin`, сам угол
    остаётся внутри ядра, а освобождается только висок за ним. При полуширине в
    90 px и `margin` 30 px это любое значение от 0.67.

    Сжимается вдоль оси, а не по горизонтали кадра: у персонажа, склонившего
    голову набок, горизонтальное сжатие открыло бы один висок и глаз напротив.
    """
    import cv2
    import numpy as np

    chin, up, side = geometry["chin"], geometry["up"], geometry["side"]

    hull_points = []
    for index in _CORE:
        offset = np.asarray(points[index], dtype=np.float64) - chin
        # Разложение по осям головы: вдоль оси оставляем как есть, поперёк жмём
        across = float(np.dot(offset, side)) * core_ratio
        along = float(np.dot(offset, up))
        hull_points.append(chin + side * across + up * along)

    core = np.zeros(shape, dtype=np.uint8)
    cv2.fillConvexPoly(core, cv2.convexHull(np.array(hull_points, dtype=np.int32)), 255)

    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * margin + 1,) * 2)
    core = cv2.GaussianBlur(cv2.dilate(core, kernel), (2 * margin + 1,) * 2, 0)

    return core.astype(np.float32) / 255.0


def _guard_band(guard: Any, geometry: dict, guard_ratio: float) -> tuple[Any, float]:
    """
    Защита, обрезанная по ширине: полоса вдоль оси лица, всё за ней отпускается.

    Написано против пряди, которую разметка отнесла к ЛИЦУ. Прядь, спускающаяся
    от виска к щеке, — тонкая и тёмная, а сегментатор работает на 256x256:
    локон растворяется в классе FACE, и дальше происходит следующее. В маску он
    не попадает, потому что маска строится из класса HAIR. Гашение защиты
    волосами (`1 - hair_soft`) его не спасает по той же причине — для разметки
    он не волосы. И, главное, вычитается он вместе со всей защитой, которая
    отнимается ПОСЛЕ дилатации: сколько маску ни расширяй, на щеке она умножится
    на ноль. Такая прядь недостижима ни одним из прежних чисел — ни `protect`
    (он меняет поле ВОКРУГ защиты, а не саму защиту), ни `core` (он жмёт ядро,
    то есть оболочку глаз, носа и рта, а класс FACE остаётся во всю щёку).

    Отсюда единственный рычаг: сузить сам ИСТОЧНИК защиты. Полуширина берётся
    не из геометрии, а из защиты — максимальный поперечный вынос её же пикселей,
    — поэтому 1.0 по построению означает «ничего не резать», и настройка
    сравнима между кадрами с разным поворотом головы.

    Режется поперёк оси головы, а не по горизонтали кадра, и по той же причине,
    что в `_face_core`: у персонажа, склонившего голову набок, горизонтальный
    рез открыл бы одну скулу и глаз напротив.

    Как и `above`, режется до расширения и размытия. Дилатация вернёт защиту
    через линию реза на `protect` обратно, размытие растянет переход — то есть
    ступеньки посреди щеки не будет, а освободится ровно то, что дальше линии
    реза на поле защиты. Отсюда и рабочая оценка: чтобы отпустить пиксель,
    отстоящий от оси на `d`, нужно `guard_ratio * полуширина + protect * высота
    лица < d`. Ядро лица возвращается поверх в любом случае, поэтому глаза, нос
    и рот этой ручкой не открываются вовсе.

    :return: суженная защита и та самая измеренная полуширина. Второе уезжает в
        мету и существует ради подбора: полуширина считается по КАДРУ, а не
        берётся из таблицы, и без неё `guard_ratio` пришлось бы угадывать
        вслепую — по два вызова fal за попытку
    """
    import numpy as np

    rows, columns = np.nonzero(guard)
    if not rows.size:
        return guard, 0.0

    chin, side = geometry["chin"], geometry["side"]
    lateral = np.abs((columns - chin[0]) * side[0] + (rows - chin[1]) * side[1])
    half = float(lateral.max())

    if guard_ratio >= 1.0 or half <= 0:
        return guard, half

    inside = lateral <= half * guard_ratio
    band = np.zeros_like(guard)
    band[rows[inside], columns[inside]] = guard[rows[inside], columns[inside]]
    return band, half


def _face_guard(
    shape: tuple[int, int],
    parsed: parsing.Parsed | None,
    points: list | None,
    face_height: float,
    protect_ratio: float,
    above: Any,
    hair_soft: Any,
    geometry: dict,
    core_ratio: float,
    guard_ratio: float,
) -> Any | None:
    """
    Защита лица: то, что вычитается из маски последним действием.

    Устроена как защита одежды в head_mask — расширяется и размывается, поэтому
    маска гаснет НАД лицом, а не по его кромке. Само лицо не получает ни единицы
    веса, а переход укладывается в поле над ним.

    **Волосы важнее защиты.** Расширение растёт наружу, то есть в прилегающие
    волосы, и на 4K это десятки пикселей по всему периметру лица. Спасённая им
    прядь — не мелочь: редактор её не сотрёт, фейссвоп вклеит лицо ПОД неё, и с
    висков готового разворота свисают тёмные ошмётки прежнего героя. Поэтому
    готовый вес гасится классом волос — мягко, размытой копией: жёсткое
    вычитание дало бы ступеньку ровно по контуру чёлки, а мягкое отдаёт редактору
    и саму чёлку, и поле вокруг неё, где ему дорисовывать освободившуюся кожу.

    Исключение одно — ядро лица, см. `_face_core`.

    Источников два, и они складываются. Класс FACE разметки — основной: он знает
    настоящую границу кожи. Контур из сетки — страховка на случай, когда
    разметка отнесла нарисованное лицо к коже тела или к фону. Из контура
    вычитаются волосы: чёлка, упавшая на бровь, — часть причёски и правится
    вместе с ней.

    Верх защиты срезается линией `above` — вот зачем. Пока лоб защищён целиком,
    граница маски проходит по открытой коже, а наша вклейка геометрию не
    выравнивает: сдвинувшаяся на несколько пикселей генерация превращает эту
    границу в рубец. Срез опускает маску до бровей, и стык уходит туда, где его
    накрывает своей растушёвкой сам фейссвоп.

    Срезается ИСТОЧНИК, до расширения и размытия. Обрежь мы готовый вес, на
    линии получилась бы ступенька от нуля к единице — тот же рубец, только в
    другом месте; так же расширение возвращает защиту через линию, а размытие
    растягивает переход на `protect_ratio` в обе стороны.

    Тем же резом и по тем же причинам защита сужается по ширине — см.
    `_guard_band`. Это единственный способ дотянуться до пряди, которую разметка
    посчитала лицом: маску за неё расширять бесполезно, защита вычитается позже.

    :return: вес 0..1, где 1 — «сюда нельзя» (либо None, если защиты нет вовсе),
        и измеренная полуширина защиты — по ней подбирается `guard_ratio`
    """
    import cv2
    import numpy as np

    guard = np.zeros(shape, dtype=np.uint8)

    if parsed is not None:
        guard = (np.asarray(parsed.face) > 127).astype(np.uint8) * 255

    if points is not None:
        polygon = np.zeros(shape, dtype=np.uint8)
        cv2.fillPoly(polygon, [head_mask.face_polygon(points)], 255)
        if parsed is not None:
            polygon = np.where(np.asarray(parsed.hair) > 127, 0, polygon).astype(np.uint8)
        guard = np.maximum(guard, polygon)

    guard = np.where(above > 0, 0, guard).astype(np.uint8)
    guard, half = _guard_band(guard, geometry, guard_ratio)

    if not guard.any() and points is None:
        # Пусто и достроить нечем. Проверка смотрит на сетку, а не на саму
        # защиту, потому что ядро лица строится по сетке и живёт отдельно от
        # источников выше: срез по лбу и сужение по ширине могут съесть источник
        # целиком, и вот тогда выход отсюда с None означал бы диффузию по глазам
        return None, half

    margin = max(1, int(round(face_height * protect_ratio)))
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * margin + 1,) * 2)
    guard = cv2.GaussianBlur(cv2.dilate(guard, kernel), (2 * margin + 1,) * 2, 0)
    guard = guard.astype(np.float32) / 255.0

    # Волосы важнее защиты — кроме ядра лица
    guard = np.minimum(guard, 1.0 - hair_soft)
    if points is not None:
        guard = np.maximum(guard, _face_core(shape, points, margin, geometry, core_ratio))

    return guard, half


def build(
    image: Any,
    dilate_ratio: float,
    feather_ratio: float,
    protect_ratio: float,
    forehead_ratio: float = 0.5,
    core_ratio: float = 1.0,
    guard_ratio: float = 1.0,
    cheek_ratio: float = 0.0,
) -> HairMask:
    """
    Строит маску причёски персонажа на шаблоне.

    :param image: шаблон, BGR numpy.ndarray
    :param dilate_ratio: расширение за контур волос, доля высоты лица. Нужно,
        чтобы у модели было куда положить новую линию роста волос и чем закрыть
        ореол старой причёски
    :param feather_ratio: ширина растушёвки краёв, доля высоты лица
    :param protect_ratio: поле защиты вокруг лица, доля высоты лица. Ноль
        означал бы, что маска подходит к глазам вплотную
    :param forehead_ratio: докуда маске можно спуститься по лбу, в долях высоты
        лица над бровями. 0 — до самых бровей: лоб целиком достаётся редактору,
        и между лицом от фейссвопа и новой причёской не остаётся полосы старой
        кожи. 0.5 и больше — линия уходит выше линии роста волос, то есть лоб не
        трогается вовсе (умолчание)
    :param core_ratio: во сколько раз сжать ядро лица ПОПЕРЁК его оси. 1.0 —
        как построено (умолчание); меньше — сильнее открыты виски и скулы, где
        застревают пряди старой причёски. Углы глаз при этом остаются накрытыми
        дилатацией, см. `_face_core`
    :param guard_ratio: какую долю ПОЛУШИРИНЫ защиты лица оставить. 1.0 — всю
        (умолчание); меньше — щёки и виски выходят из-под защиты целиком, и
        только этим достаётся прядь, которую разметка отнесла к классу лица.
        Ядро лица возвращается поверх среза, см. `_guard_band`
    :param cheek_ratio: докуда спускается полоса вдоль щеки, доли высоты лица
        НИЖЕ подбородка. 0 — полосы нет (умолчание), и область строится ровно по
        разметке. Больше нуля — по обе стороны от оси лица добавляется область,
        объявленная причёской без разметки вовсе: единственное, чем берётся
        локон, который сегментатор не отнёс ни к волосам, ни к лицу, см.
        `_cheek_bands`
    :raises NoFaceDetectedError: персонажа не нашли ни детектором, ни разметкой
    """
    import cv2
    import numpy as np

    if (
        dilate_ratio < 0
        or feather_ratio < 0
        or protect_ratio < 0
        or forehead_ratio < 0
        or core_ratio < 0
        or guard_ratio < 0
        or cheek_ratio < 0
    ):
        raise InvalidImageError(
            "Доли маски волос не могут быть отрицательными",
            {
                "dilate": dilate_ratio,
                "feather": feather_ratio,
                "protect": protect_ratio,
                "forehead": forehead_ratio,
                "core": core_ratio,
                "guard": guard_ratio,
                "cheek": cheek_ratio,
            },
        )

    shape = image.shape[:2]
    points = head_mask.try_landmarks(image)
    parsed = parsing.parse(image)

    geometry = head_mask.face_geometry(points) if points else None
    parsed_seed = None

    if geometry is None:
        fallback = head_mask.parsed_geometry(parsed) if parsed else None
        if fallback is None:
            raise NoFaceDetectedError(
                "На шаблоне не найден персонаж: сетка лица пуста, разметка тоже",
                {
                    "parsing_available": parsing.available(),
                    # Причёска — единственное, ради чего здесь нужна геометрия.
                    # Отказ от неё возвращает нас к переносу одного лица
                    "hint": "перенос без причёски работает без локальной геометрии: "
                    "ML_REFINE_STRATEGY=face_swap",
                },
            )
        parsed_seed = fallback.pop("seed")
        geometry = fallback

    face_height = geometry["face_height"]
    seed = _seed(shape, points, parsed_seed)

    close = max(1, int(round(min(shape) * _CLOSE_RATIO)))
    region = _own_hair(parsed, seed, close) if parsed is not None else None
    source = "parsing"

    if region is None:
        region = _fallback_ring(shape, geometry, points)
        source = "ellipse"
        if region is None:
            raise NoFaceDetectedError(
                "На шаблоне не нашлось волос: класс разметки пуст, сетки лица нет",
                {"parsing": parsed is not None, "landmarks": points is not None},
            )
        log.warning(
            "маска волос построена кольцом вокруг лица: формы причёски мы не знаем",
            extra={"parsing": parsed is not None},
        )

    # Сами волосы — отдельно от всего, что к области добавится дальше. По ним
    # гасится защита лица, и по ним же считается остаток: сколько пикселей
    # старой причёски маска не забрала
    hair_only = region
    hair_px = int(np.count_nonzero(hair_only > 127))

    # Полоса вдоль щёк — область, объявленная причёской без разметки. Всё
    # остальное в этом модуле спрашивает сегментатор, и локон, которого он не
    # видит ни волосами, ни лицом, недостижим ничем: расширять нечего, отпускать
    # нечего. Складывается с волосами ДО дилатации — дальше полоса живёт на
    # общих правах и растёт наружу вместе с ними
    cheeks = _cheek_bands(shape, geometry, cheek_ratio)
    claimed = hair_only if cheeks is None else np.maximum(hair_only, cheeks)
    region = claimed

    # Лоб. Кожа выше линии бровей добавляется в область явно, а не достаётся ей
    # расширением: расширение растёт от волос во все стороны сразу, и, дотянув
    # его до бровей, мы получили бы маску и на висках, и на скулах.
    above = _above_brows(shape, geometry, forehead_ratio)
    forehead_px = 0
    if parsed is not None:
        forehead = np.minimum((np.asarray(parsed.face) > 127).astype(np.uint8), above // 255)
        forehead_px = int(np.count_nonzero(forehead))
        region = np.maximum(claimed, forehead * 255)

    # Расширение и растушёвка — тем же порядком и по той же причине, что у маски
    # головы: спад обязан лечь целиком СНАРУЖИ, иначе сами волосы уедут в модель
    # полупрозрачными и от старой причёски останется призрак по контуру.
    dilate = int(round(face_height * dilate_ratio))
    feather = int(round(face_height * feather_ratio))

    grow = dilate + feather
    mask = region
    if grow > 0:
        mask = cv2.dilate(mask, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * grow + 1,) * 2))
    if feather > 0:
        mask = cv2.GaussianBlur(mask, (2 * feather + 1, 2 * feather + 1), 0)

    grown = mask

    # Мягкая копия волос: ею гасится защита лица. Только размытие, без
    # расширения, и это принципиально. Расширенная копия сдвинула бы открытую
    # область на кожу по всей линии роста волос — то есть на виски и скулы, где
    # волосы граничат с лицом всегда. Размытие же ставит переход ровно на контур
    # пряди: внутри неё защиты нет, на коже она возвращается за пару десятков
    # пикселей. Поле для растушёвки у маски и так своё, см. `grow` выше.
    #
    # Гасится защита не классом волос, а ВСЕМ, что мы объявили причёской, —
    # вместе с полосой вдоль щёк. Без этого полоса не работала бы вовсе: класс
    # FACE растянут на всю щёку, защита вычитается ПОСЛЕ дилатации, и на щеке
    # маска умножилась бы на ноль. Ядро лица накладывается поверх и здесь, так
    # что глаза, нос и рот полосой не открываются ни при каком её размере.
    soft = max(1, feather)
    hair_soft = cv2.GaussianBlur(claimed, (2 * soft + 1,) * 2, 0).astype(np.float32) / 255.0

    # Защита лица — ПОСЛЕ расширения, и это главное свойство этой маски.
    # Вычитать лицо до дилатации бессмысленно: она вернула бы маску на него, и
    # на 4K — десятками пикселей, то есть прямо на брови и веки.
    guard, guard_half = _face_guard(
        shape,
        parsed,
        points,
        face_height,
        protect_ratio,
        above,
        hair_soft,
        geometry,
        core_ratio,
        guard_ratio,
    )
    if guard is not None:
        mask = (mask.astype(np.float32) * (1.0 - guard)).astype(np.uint8)
    else:
        log.warning("лицо на шаблоне нечем защитить: ни разметки, ни сетки")

    open_px = int(np.count_nonzero(mask > 127))
    share = open_px / float(shape[0] * shape[1])

    # ГДЕ остались невзятые волосы, а не только сколько их. Число без места
    # неинформативно: у остатка два разных виновника, и лечатся они разными
    # ручками, противоположными по действию.
    #
    # Пиксель класса волос попадает в область по построению и после дилатации
    # стоит в маске на 255. Уменьшить его может только защита — больше в этой
    # функции ничего маску не трогает. Значит, остаток держит либо суженная
    # защита (тогда он лежит НЕ ДАЛЬШЕ `guard_reach_px` от оси лица), либо ядро,
    # которое накладывается ПОСЛЕ среза и потому дотягивается дальше него.
    #
    # Отсюда правило чтения: остаток внутри guard_reach_px — крутить guard,
    # снаружи — крутить core. Раньше это приходилось выводить из головы, по два
    # вызова fal за догадку.
    left = (hair_only > 127) & (mask <= 127)
    left_px = int(np.count_nonzero(left))
    left_span = None
    if left_px:
        left_rows, left_columns = np.nonzero(left)
        chin, side = geometry["chin"], geometry["side"]
        left_lateral = np.abs((left_columns - chin[0]) * side[0] + (left_rows - chin[1]) * side[1])
        left_span = [round(float(left_lateral.min()), 1), round(float(left_lateral.max()), 1)]

    protect_px = max(1, int(round(face_height * protect_ratio)))

    # Что стало с полосой вдоль щёк — и, главное, что о ней думает разметка.
    #
    # Пара cheek_px / cheek_hair_px и есть ответ на вопрос, который стоил
    # прогона: сколько полоса накрыла и сколько из накрытого сегментатор считал
    # волосами. Почти ноль во втором числе при большом первом означает ровно то,
    # что мы и увидели вживую, — локона для разметки не существует, и все ручки,
    # работающие с классом волос, до него не дотянутся по построению.
    #
    # cheek_open_px отвечает на следующий вопрос: дошла ли полоса до маски.
    # Заметно меньше cheek_px — её съела защита лица, и это единственный случай,
    # когда после включения полосы всё равно надо крутить guard
    cheek_px = cheek_hair_px = cheek_open_px = None
    if cheeks is not None:
        inside_cheeks = cheeks > 127
        cheek_px = int(np.count_nonzero(inside_cheeks))
        cheek_hair_px = int(np.count_nonzero(inside_cheeks & (hair_only > 127)))
        cheek_open_px = int(np.count_nonzero(inside_cheeks & (mask > 127)))

    # Сколько ткани попало под правку. Ноль тут недостижим и не нужен: под
    # длинными волосами лежит одежда, и, убирая их, эту одежду придётся
    # дорисовать. Но если число сравнимо со всей тканью кадра, маска уехала с
    # головы на костюм — и объяснит перерисованный жилет именно эта строка.
    clothes_px = None
    if parsed is not None:
        clothes = np.asarray(parsed.clothes) > 127
        clothes_px = int(np.count_nonzero(clothes & (mask > 127)))

    meta = {
        "source": source,
        "landmarks": points is not None,
        "parsing": parsed is not None,
        "face_height": round(face_height, 1),
        "hair_px": hair_px,
        # Сколько кожи лба вошло в область. Ноль при малом forehead_ratio
        # означает, что линия бровей посчитана мимо — стык останется на лбу
        "forehead_px": forehead_px,
        "forehead_ratio": forehead_ratio,
        "core_ratio": core_ratio,
        "guard_ratio": guard_ratio,
        "cheek_ratio": cheek_ratio,
        # Полоса вдоль щёк: сколько накрыла, сколько из этого разметка считала
        # волосами и сколько дошло до маски. None — полоса выключена
        "cheek_px": cheek_px,
        "cheek_hair_px": cheek_hair_px,
        "cheek_open_px": cheek_open_px,
        # Полуширина защиты в пикселях — то, от чего guard_ratio берёт долю. По
        # ней и подбирается значение: чтобы отпустить прядь, отстоящую от оси
        # лица на d, нужно guard_ratio × guard_half_px + protect_px < d
        "guard_half_px": round(guard_half, 1),
        "protect_px": protect_px,
        # Докуда защита достаёт ПОСЛЕ среза по ширине. Граница ответственности
        # двух ручек: остаток волос ближе этого числа к оси лица держит guard,
        # дальше — core, потому что ядро накладывается поверх среза
        "guard_reach_px": round(guard_ratio * guard_half + protect_px, 1),
        "dilate_px": dilate,
        "feather_px": feather,
        # Сколько маски съела защита лица. Ноль означает, что защита не сработала
        # вовсе, — а значит, диффузия пойдёт по глазам
        "protected_px": int(np.count_nonzero((grown > 127) & (mask <= 127))),
        # Сколько пикселей СТАРЫХ ВОЛОС осталось вне маски. Растёт — значит,
        # редактор их не сотрёт, а фейссвоп вклеит лицо под них: на висках и
        # лбу повиснут тёмные ошмётки прежнего героя. Ноль недостижим — ядро
        # лица прядь поверх глаза не отдаёт, — но это единицы пикселей.
        #
        # Читать его надо с одной оговоркой, и стоила она прогона: это остаток
        # КЛАССА волос, то есть меряется он мнением сегментатора. Прядь, которую
        # разметка не отнесла к волосам вовсе, сюда не попадает ни одним
        # пикселем — единицы здесь прекрасно уживаются с локоном во всю щёку.
        # Про него отвечает пара cheek_px / cheek_hair_px
        "hair_left_px": left_px,
        # Поперечный вынос остатка от оси лица: [ближний, дальний]. Читается
        # вместе с guard_reach_px — см. комментарий у его вычисления
        "hair_left_span_px": left_span,
        "clothes_px": clothes_px,
        "open_px": open_px,
        "open_share": round(share, 4),
    }
    log.info("маска волос на шаблоне построена", extra=meta)

    if open_px == 0:
        raise NoFaceDetectedError(
            "Маска волос пуста: защита лица съела область целиком",
            {**meta, "hint": "уменьшите ML_HAIR_PROTECT_RATIO"},
        )
    if share > 0.35:
        log.warning("маска волос накрыла треть кадра", extra={"open_share": share})

    if hair_px and left_px > hair_px * _LEFT_WARN_SHARE:
        # Ровно тот брак, ради которого волосы объявлены важнее защиты: не
        # попавшие в маску пряди редактор не сотрёт, а фейссвоп вклеит лицо под
        # них — и с висков разворота повиснут тёмные ошмётки. Вместе с числом
        # уходит и место: по нему видно, какую из двух ручек крутить
        log.warning(
            "часть старых волос осталась вне маски: на лице возможны остатки причёски",
            extra={
                "hair_left_px": left_px,
                "hair_left_span_px": left_span,
                "guard_reach_px": meta["guard_reach_px"],
                "hair_px": hair_px,
                "protect_ratio": protect_ratio,
            },
        )

    return HairMask(mask=mask, face_height=face_height, meta=meta)
