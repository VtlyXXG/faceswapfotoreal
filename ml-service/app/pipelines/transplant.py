def _full_frame_landmarks(image: Any) -> list[tuple[int, int]] | None:
    """
    Сетка в координатах ПОЛНОГО кадра, даже если детектор нашёл лицо не сразу.

    MediaPipe не видит лицо мельче ~20% кадра, а на развороте оно занимает
    10-17%. Запасной путь — увеличенное окно вокруг предполагаемой головы, но
    его координаты обязаны быть пересчитаны обратно: подобие, построенное по
    точкам из кропа, увезёт голову на смещение этого кропа.
    """
    import cv2

    points = head_mask.try_landmarks(image)
    if points is not None:
        return points

    height, width = image.shape[:2]
    x0, y0 = int(width * 0.25), 0
    x1, y1 = int(width * 0.75), int(height * 0.6)
    crop = image[y0:y1, x0:x1]
    if crop.size == 0:
        return None

    scale = max(1.0, 900.0 / max(1, max(crop.shape[:2])))
    if scale > 1.0:
        crop = cv2.resize(crop, None, fx=scale, fy=scale, interpolation=cv2.INTER_CUBIC)

    points = head_mask.try_landmarks(crop)
    if points is None:
        return None
    return [(int(x / scale) + x0, int(y / scale) + y0) for x, y in points]


def _own_head(image: Any, points: list[tuple[int, int]]) -> tuple[Any, Any] | None:
    """
    Силуэт головы НАШЕГО персонажа: классы HAIR и FACE, связные с его лицом.

    Отсюда берут и размер головы (`head_extent`), и область стирания
    (`head_silhouette`) — источник один, и разойтись им негде.

    :return: пара «силуэт 0/1 uint8, разметка» либо None, если разметки нет или
        головы на ней не видно. Разметка отдаётся наружу, а не запрашивается
        второй раз: она же отвечает, где ткань и кожа, а сегментатор стоит
        десятки миллисекунд на кадр
    """
    import cv2
    import numpy as np

    parsed = parsing.parse(image)
    if parsed is None:
        return None

    hair = (np.asarray(parsed.hair) > 127).astype(np.uint8)
    face = (np.asarray(parsed.face) > 127).astype(np.uint8)
    head = np.maximum(hair, face)
    if not head.any():
        return None

    # Смыкаем разрывы между прядями тем же ядром, что и `_region_from_parsing`,
    # иначе голова распадётся на компоненты на первом же просвете
    close = max(1, int(round(min(head.shape) * 0.004)))
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * close + 1,) * 2)
    head = cv2.morphologyEx(head, cv2.MORPH_CLOSE, kernel)

    seed = np.zeros(image.shape[:2], dtype=np.uint8)
    cv2.fillPoly(seed, [head_mask.face_polygon(points)], 1)
    own = head_mask.component_of(head, seed)
    return (head if own is None else own), parsed


def _strand_matte(image: Any, own: Any, parsed: Any, face_height: float) -> tuple[Any, dict]:
    """
    Отдельные волоски прежнего героя, которых разметка не видит.

    ЗАЧЕМ. Силуэт стирания — это классы HAIR и FACE, а сегментатор работает на
    сетке 256x256: на нашем развороте одна его клетка это 5.4 пикселя кадра.
    Прядь толщиной в пиксель-другой, лежащая по небу, в класс не попадает
    никогда — она не «волосы» и не «фон», она их СМЕСЬ, и правильный ответ про
    неё не класс, а доля. Замерено на готовых кадрах: 109 пикселей волосков по
    небу у dino1_id4 и 40 у dino1_id6 дошли до печати ПОБИТОВО — прежний герой
    остался в книге прядями поверх новой головы, и глазами они заметны, потому
    что тёмное на светлом. Разметка окна головы, увеличенного в пять раз,
    добавляет к силуэту 1.2% причёски и этих прядей не находит тоже — значит,
    дело не в разрешении, и семантикой задача не решается в принципе.

    КАК. Пиксель кольца раскладывается на смесь двух цветов: волос и фона.
    Оба берутся не из головы, а из кадра — усреднением по своей стороне
    (`cv2.blur` по маске, делённый на blur самой маски, то есть среднее ровно по
    тем пикселям, что принадлежат стороне). Доля волоса — проекция на отрезок
    между ними. Это школьное разложение, и держится оно на двух проверках:

      * НЕВЯЗКА. Смесь обязана сойтись с настоящим цветом пикселя. Тёмная
        полоска футболки и ветка в листве по яркости на прядь похожи, а по цвету
        в смесь «волосы плюс небо» не ложатся, и невязка их отсекает.
      * СВЯЗНОСТЬ. Прядь растёт из причёски. Одиноко стоящее пятно — это не
        прядь, а птеродактиль в небе, и стирать его нельзя.

    Сверх этого действует запрет на ткань и открытую кожу: последнее слово за
    ними, как и в `head_mask._fabric_guard`. Одежда персонажа обязана дойти до
    печати без изменений, и цена ошибки тут несимметрична — лишний волосок в
    кадре хуже смотрится, но перерисованный воротник непоправим.

    :return: 0/1 uint8 и отчёт. Маска бинарная, а не мягкая, намеренно: LaMa
        достраивает область как целое, и просить у неё полупрозрачное стирание
        нечем — она либо переписывает пиксель, либо нет. Смесь «20% волоса и 80%
        неба» честнее целиком отдать под небо, тем более что альфа считается
        только там, где вокруг действительно фон
    """
    import cv2
    import numpy as np

    band = max(2, int(round(face_height * _MATTE_BAND_RATIO)))
    core = own > 0

    # Ткань и кожа тела — не волосы, и разложение на них не запускается вовсе.
    #
    # Вето применяется по СЪЁЖЕННОМУ классу, и это не поблажка. Сегментатор
    # размечает кадр на сетке 256x256: положение границы класса он знает с
    # точностью до клетки, а клетка здесь 5.4 пикселя. У самой границы в классе
    # «одежда» оказывается голое небо, а вместе с ним и лежащие по нему пряди.
    # Замерено на dino1: вето по сырому классу накрывает 67% дошедших до печати
    # волосков на id4 и 10% на id6, по съёженному — 100% на обоих, а лишнего
    # стирания прибавляется 540 пикселей. Съёженный класс запрещает ровно то, в
    # чём разметка уверена.
    fabric = (np.asarray(parsed.clothes) > 127) | (np.asarray(parsed.skin) > 127)
    cell = max(1, int(round(max(image.shape[:2]) / _PARSING_GRID)))
    veto = cv2.erode(fabric.astype(np.uint8), cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE, (2 * cell + 1,) * 2)) > 0

    meta = {"band_px": band, "cell_px": cell}

    # Окно вчетверо шире кольца: уже — и на тонкой пряди среднее фона наберётся
    # из неё самой, то есть прядь объяснит сама себя и альфа выйдет нулевой
    window = (4 * band) | 1
    frame = image.astype(np.float32)
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * band + 1,) * 2)

    def side_colour(mask_bool: Any) -> tuple[Any, Any]:
        """Средний цвет по СВОЕЙ стороне в окрестности каждого пикселя."""
        weight = mask_bool.astype(np.float32)
        total = cv2.blur(weight, (window, window))
        colour = cv2.blur(frame * weight[..., None], (window, window))
        return colour / np.maximum(total, 1e-6)[..., None], total

    # Цвет волос берётся всегда по плотной копне, а не по уже найденным
    # волоскам: те сами полупрозрачны, и подмешивать их в опорный цвет значит
    # уводить его к фону с каждым шагом
    hair_colour, hair_weight = side_colour(cv2.erode(own, np.ones((3, 3), np.uint8)) > 0)

    # Кольцо шагает вдоль пряди, а не расширяется везде. Длинный волосок уходит
    # от копны дальше кольца — на dino1 до 31 px при кольце 16, — но он связная
    # линия, и найденный кусок сам служит опорой для следующего шага. Широкое
    # кольцо вместо этого замерено и отвергнуто: на 0.20 высоты лица оно
    # дотягивается до тени под челюстью и до шеи, то есть стирает уже не волосы.
    found = np.zeros(own.shape, bool)
    for _ in range(_MATTE_PASSES):
        base = core | found
        grown = cv2.dilate(base.astype(np.uint8), kernel) > 0
        unknown = grown & ~base & ~veto
        if not unknown.any():
            break

        back_colour, back_weight = side_colour(~grown)
        delta = hair_colour - back_colour
        contrast = np.linalg.norm(delta, axis=2)
        usable = unknown & (contrast > _MATTE_CONTRAST) & (hair_weight > 1e-4) \
            & (back_weight > 1e-4)
        if not usable.any():
            break

        alpha = np.zeros(own.shape, np.float32)
        num = ((frame - back_colour) * delta).sum(axis=2)
        alpha[usable] = np.clip(num[usable] / (contrast[usable] ** 2), 0.0, 1.0)
        residual = np.linalg.norm(frame - (back_colour + alpha[..., None] * delta), axis=2)
        alpha[residual > _MATTE_RESIDUAL] = 0.0

        fresh = alpha > _MATTE_FLOOR
        if not fresh.any():
            break
        found |= fresh

    strand = found.astype(np.uint8)
    meta["raw_px"] = int(np.count_nonzero(strand))

    # Прядь растёт из причёски: оставляем только то, что связано с силуэтом
    joined = head_mask.component_of(np.maximum(strand, own), own)
    strand = np.zeros(own.shape, np.uint8) if joined is None else (joined & ~core).astype(np.uint8)

    meta["matte_px"] = int(np.count_nonzero(strand))
    return strand, meta


def head_silhouette(image: Any, points: list[tuple[int, int]], face_height: float) -> Any:
    """
    Где стоит стирать старую голову: её собственный силуэт, и ничего сверх.

    ПОЧЕМУ НЕ РАБОЧАЯ МАСКА. Маска из `head_mask.build` расширена на
    `dilate + feather` — на замеренном кадре это 29 пикселей за силуэт. В этом
    кольце шаблонный фон ЦЕЛ, и стирать его незачем: LaMa вернёт туда свою
    догадку, и на месте чёткого горного хребта окажется размытое пятно. Замер
    трёх вариантов области стирания (стык заплатки с нетронутым шаблоном /
    остаток старой головы в пикселях):

        по всей рабочей маске   18.46 / 75
        по эрозии этой маски    12.97 / 260-714
        по силуэту разметки     см. `SCALE_MODE`-подобный выбор ниже

    Эрозия отвергнута замером: она снимает одинаково во все стороны, а голова
    не круг — где-то срезает лишнее, где-то оставляет волосы прежнего героя.
    Силуэт знает форму, и потому запас поверх него нужен маленький: только на
    полупрозрачную кромку антиалиасинга, которую разметка относит к фону.

    ЧЕГО СИЛУЭТУ НЕ ХВАТАЕТ. Отдельных волосков: их разметка не относит к
    волосам ни на каком разрешении, и на готовых кадрах они доходили до печати
    нетронутыми. Их добавляет `_strand_matte` — разложением цвета, а не классом.
    Слепое расширение силуэта вместо этого замерено и отвергнуто: запас
    0.15 высоты лица даёт у dino1 полосу в 15 259 px, из которых 11% ложится на
    одежду и 12% на открытую кожу — ровно то, от чего защищает `clothes_guard`,
    — а у dino2 79% полосы приходится на детальную листву, которую LaMa вернёт
    размытым пятном.

    :return: маска 0..255 либо None, если разметки нет
    """
    import cv2
    import numpy as np

    head = _own_head(image, points)
    if head is None:
        return None
    own, parsed = head

    grow = max(1, int(round(face_height * _ERASE_DILATE_RATIO)))
    feather = max(1, int(round(face_height * _ERASE_FEATHER_RATIO)))
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * grow + 1,) * 2)
    mask = cv2.dilate((own * 255).astype(np.uint8), kernel)
    mask = cv2.GaussianBlur(mask, (2 * feather + 1,) * 2, 0)

    strand, meta = _strand_matte(image, own, parsed, face_height)
    if not strand.any():
        log.info("отдельных прядей за силуэтом не найдено", extra=meta)
        return mask

    # Волосок берётся вместе с собственной кромкой: на границе он полупрозрачен
    # и с одним лишь ядром пряди в кадре остаётся его же ореол. Запас тот же,
    # что у силуэта, и он тоже не выходит за пределы фона
    strand = cv2.dilate(strand, cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE, (2 * grow + 1,) * 2))
    cell = max(1, int(round(max(image.shape[:2]) / _PARSING_GRID)))
    fabric = (np.asarray(parsed.clothes) > 127) | (np.asarray(parsed.skin) > 127)
    strand[cv2.erode(fabric.astype(np.uint8), cv2.getStructuringElement(
        cv2.MORPH_ELLIPSE, (2 * cell + 1,) * 2)) > 0] = 0

    meta["erase_px"] = int(np.count_nonzero(mask > 127))
    meta["added_px"] = int(np.count_nonzero((strand > 0) & (mask <= 127)))
    # Сколько прядей попало в сырой класс ткани и кожи. Ноль здесь не нужен:
    # волосы лежат ПОВЕРХ плеча, и разметка их плечу и отдаёт. Но если число
    # сравнимо с `added_px`, значит стирается уже не прядь, а воротник, — и
    # смотреть при жалобе на перерисованную одежду надо сюда
    meta["on_fabric_px"] = int(np.count_nonzero((strand > 0) & fabric))
    log.info("к силуэту добавлены пряди прежнего героя", extra=meta)
    return np.maximum(mask, strand * 255)


def head_extent(image: Any, points: list[tuple[int, int]]) -> float | None:
    """
    Размер ГОЛОВЫ в пикселях: корень из площади силуэта «волосы плюс лицо».

    Существует потому, что `face_height` (подбородок → брови) описывает лицо, а
    не голову. У ребёнка помладше черепная коробка относительно лица заметно
    крупнее, и подгонка по высоте лица раздувает вместе с ней весь череп: на
    замере это дало голову, великоватую для плеч шаблона, при коррекции 1.28.

    Корень из площади, а не высота описанного прямоугольника: прямоугольник
    целиком определяется двумя крайними прядями, и одна торчащая прядь меняет
    его сильнее, чем вся остальная голова.

    :return: масштабный измеритель либо None, если разметки нет
    """
    import numpy as np

    head = _own_head(image, points)
    if head is None:
        return None
    area = int(np.count_nonzero(head[0]))
    return float(np.sqrt(area)) if area else None


def _scale(source: dict, target: dict, mode: str | None = None) -> float:
    """
    Во сколько раз увеличить генерацию, чтобы её голова села в шаблонную.

    :param mode: чем мерить — `face`, `head` или `blend`. None означает
        `SCALE_MODE`, то есть выбранный замером умолчательный режим. Явное
        значение нужно там, где генерация приносит ЧУЖУЮ причёску: `head`
        меряет силуэт «волосы плюс лицо», и с переносом причёски эта мерка
        становится неверной по построению — пышные волосы ужмут лицо, гладкие
        раздуют. Замер ниже сделан на прогонах, где причёска бралась от шаблона,
        и на перенос причёски он не переносится.

    ЗАМЕР НА 21 КАДРЕ, по которому выбран режим. Мерилось отношение размера
    головы в готовом кадре к размеру головы шаблона (идеал — единица) и число
    кадров с промахом больше 15% хоть по одной мерке:

        режим   голова: среднее / худшая   промахов >15%
        face          0.988 / 1.314              5
        head          0.977 / 0.904              3
        blend         0.970 / 0.805              6

    `face` даёт худший выброс: на кадре с малышом голова выходит на 31% крупнее
    шаблонной и заметно не по плечам. `blend` оказался не компромиссом, а худшим
    вариантом по числу промахов — ошибки не гасят друг друга, а размазываются по
    всем кадрам. `head` и по среднему, и по худшему, и по числу промахов лучше
    обоих, и глазами тоже: на провальном кадре он ставит 0.97 вместо 1.28.

    ОГОВОРКА ПРО ВТОРУЮ МЕРКУ. Отношение высот ЛИЦА в готовом кадре считалось
    тоже, и там `head` показывал худший результат (0.69). Проверка глазами его не
    подтвердила: дефекта на этом кадре нет. Сетка лица на composite ложится
    неустойчиво — вокруг вклейки лежат пиксели шаблона и растушёвка, — поэтому
    мерка по лицу на готовом кадре шумит и решающей не бралась.
    """
    import numpy as np

    mode = mode or SCALE_MODE
    by_face = float(target["face_height"]) / max(1e-6, float(source["face_height"]))
    extent_s, extent_t = source.get("head_extent"), target.get("head_extent")
    if mode == "face" or not extent_s or not extent_t:
        return by_face

    by_head = float(extent_t) / max(1e-6, float(extent_s))
    if mode == "head":
        return by_head
    return float(np.sqrt(by_face * by_head))


def similarity(source: dict, target: dict, scale_mode: str | None = None) -> Any:
    """
    Матрица 2x3, сажающая голову `source` на место головы `target`.

    Три величины задают подобие полностью: отношение размеров — масштаб, угол
    между осями головы — поворот, подбородок — неподвижная точка. Поворот
    берётся именно как угол между осями, а не как разность их наклонов к
    вертикали: второе ломается на кадрах, где голова наклонена больше 90°.

    Чем меряется масштаб — см. `_scale`: у мерки по лицу и у мерки по голове
    разные слабые места, и выбор между ними сделан замером, а не вкусом.
    """
    import numpy as np

    scale = _scale(source, target, scale_mode)
    up_s, up_t = np.asarray(source["up"], float), np.asarray(target["up"], float)
    angle = float(np.arctan2(up_t[0] * up_s[1] - up_t[1] * up_s[0],
                             up_t[0] * up_s[0] + up_t[1] * up_s[1]))

    cos, sin = np.cos(angle) * scale, np.sin(angle) * scale
    rotation = np.array([[cos, -sin], [sin, cos]], dtype=np.float64)

    chin_s = np.asarray(source["chin"], float)
    chin_t = np.asarray(target["chin"], float)
    shift = chin_t - rotation @ chin_s

    matrix = np.zeros((2, 3), dtype=np.float64)
    matrix[:, :2] = rotation
    matrix[:, 2] = shift
    return matrix


# Запас вокруг головы шаблона, в высотах лица: дальше маске, посчитанной по
# генерации, ходу нет. Половина выбрана замером, а не на глаз — см. `_allowance`.
_ALLOWANCE_RATIO = 0.5


def _allowance(head_old: Any, feather_ratio: float) -> Any:
    """
    Докуда маске по генерации разрешено доходить.

    ЗАЧЕМ. Итоговая маска — объединение двух: посчитанной по шаблону (постоянна)
    и посчитанной по ВЫРОВНЕННОЙ ГЕНЕРАЦИИ (каждый раз новая). Вторая иногда
    оказывается крупнее или уезжает подгонкой, и тогда замена уходит с головы на
    туловище: в кадр попадают руки и плечи генерации поверх шаблонных. На стенде
    (5 страниц x 3 донора x 2 броска) это случилось на 7 кадрах из 29, на всех
    страницах без исключения, с заходом до 67 px ниже шаблонной маски.

    ПОЧЕМУ ПОЛОВИНА ВЫСОТЫ ЛИЦА, А НЕ ВПРИТЫК. Впритык — это не «строго», это
    неверно: у длинноволосой девочки на коротко стриженном персонаже причёска
    ЗАКОННО выходит за голову шаблона. Замер долей заменённого вне шаблонной
    маски:

        донор              впритык   с запасом 0.5
        donor2 (короткие)     6.0%          0.0%
        donor6                12.3%          2.8%
        фото заказчика         9.4%          1.8%

    Впритык срезало бы у donor6 в среднем 12% нарисованного, и это волосы.
    С запасом в полвысоты лица цена падает до 2-3% у длинноволосых и до нуля у
    коротко стриженного, а переполнение при этом остаётся ограниченным.

    КРАЙ РАЗМЫТ той же растушёвкой, что у самих масок. Жёсткая отсечка дала бы
    шов ровно там, где ограничение сработало, — то есть поменяла бы один
    заметный дефект на другой.
    """
    import cv2
    import numpy as np

    radius = max(1, int(round(head_old.face_height * _ALLOWANCE_RATIO)))
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * radius + 1,) * 2)
    grown = cv2.dilate((np.asarray(head_old.mask) > 127).astype(np.uint8) * 255, kernel)

    feather = max(1, int(round(head_old.face_height * feather_ratio)))
    return cv2.GaussianBlur(grown, (0, 0), feather)


def transplant(
    template: Any,
    generated: Any,
    dilate_ratio: float,
    feather_ratio: float,
    neck_ratio: float,
    match_tone: bool = True,
    match_skin: bool = True,
    plate: Any = None,
    scale_mode: str | None = None,
) -> Transplanted:
    """
    Возвращает шаблон, в котором заменена только голова.

    ЧТО ЛОЖИТСЯ ПОД СТАРУЮ ГОЛОВУ. Маска шаблона и маска новой головы совпадают
    не полностью: у прежнего героя своя причёска, у нового своя, и между ними
    остаётся зона, которую надо очистить от старой головы, но накрыть новой
    нечем. На замере это 8819 пикселей из 49874 — шестая часть маски.

    Класть туда выровненную генерацию НЕЛЬЗЯ, и это проверено дорого: подобие
    сдвигает её по вертикали (на замеренном кадре на 11 пикселей), вместе с
    головой уезжают её собственные воротник и плечи, и на стыке шеи выходит два
    воротника вместо одного. Замер: 3458 пикселей результата расходятся с
    шаблоном больше чем на 32 уровня, максимум 207.

    Правильное содержимое там — продолжение шаблонной одежды и фона, то есть
    стирание. Его делает LaMa на GPU-сервере (`/v1/erase`), и результат
    передаётся сюда параметром `plate`.

    :param template: шаблон-разворот, BGR numpy.ndarray. Источник всего, что не
        голова, — и источник побитово
    :param generated: ответ генеративного редактора, BGR numpy.ndarray
    :param match_tone: привести тон генерации к шаблону перед вклейкой. Считается
        по пикселям вне ОБЕИХ масок, где обе картинки изображают одно и то же
    :param match_skin: привести отдельно тон КОЖИ — см. `_match_skin`. Общая
        подгонка тона этого не делает и сделать не может: она считается по фону,
        а разрыв возникает на шее, где светлая кожа донора встречается со смуглой
        кожей персонажа
    :param scale_mode: чем мерить размер головы — `face`, `head` или `blend`.
        None берёт `SCALE_MODE`. Умолчание выбрано замером на прогонах, где
        причёска доставалась от шаблона; как только генерация приносит свою,
        мерка по силуэту головы становится неверной по построению — см. `_scale`
    :param plate: шаблон со стёртой головой. Стирать ОБЯЗАТЕЛЬНО той же маской,
        которой подложка потом применяется, то есть `head_silhouette`, — это
        требование корректности, а не экономии. Проверено дорого: плита,
        посчитанная по широкой рабочей маске и применённая по узкому силуэту,
        даёт на плече тёмный прямоугольный блок с резкими краями. LaMa
        достраивает область как целое, и вырезанный из её реконструкции кусок с
        собственным окружением не согласован.

        None — старая голова накрывается генерацией, и на стыке шеи появляется
        описанное выше удвоение; путь оставлен рабочим на случай недоступного
        сервера, но сопровождается предупреждением в логе
    :raises InvalidImageError: голову не нашли на шаблоне или на генерации, либо
        подобие вышло за пределы правдоподобного
    """
    import cv2
    import numpy as np

    if template.ndim != 3 or generated.ndim != 3:
        raise InvalidImageError("Пересадка ждёт цветные изображения")

    height, width = template.shape[:2]
    if generated.shape[:2] != (height, width):
        generated = cv2.resize(generated, (width, height), interpolation=cv2.INTER_LANCZOS4)

    points_t = _full_frame_landmarks(template)
    points_g = _full_frame_landmarks(generated)
    if points_t is None:
        raise InvalidImageError("На шаблоне не найдена голова персонажа")
    if points_g is None:
        raise InvalidImageError("На генерации не найдена голова")

    geometry_t = head_mask.face_geometry(points_t)
    geometry_g = head_mask.face_geometry(points_g)
    geometry_t["head_extent"] = head_extent(template, points_t)
    geometry_g["head_extent"] = head_extent(generated, points_g)
    matrix = similarity(geometry_g, geometry_t, scale_mode)

    scale = float(np.sqrt(matrix[0, 0] ** 2 + matrix[0, 1] ** 2))
    angle = float(np.degrees(np.arctan2(matrix[1, 0], matrix[0, 0])))
    if not _SCALE_MIN <= scale <= _SCALE_MAX or abs(angle) > _ANGLE_LIMIT:
        # Не подгоняем: подобие за этими пределами означает, что редактор
        # перерисовал сцену, а не голову, и вклейка выдаст коллаж
        raise InvalidImageError(
            "Голова генерации не приводится к шаблонной подобием",
            {"scale": round(scale, 3), "angle": round(angle, 1)},
        )

    aligned = cv2.warpAffine(
        generated, matrix, (width, height),
        flags=cv2.INTER_LANCZOS4, borderMode=cv2.BORDER_REPLICATE,
    )

    # Маска строится по ВЫРОВНЕННОЙ генерации, а не по шаблону: заменяем мы ту
    # голову, которая теперь в кадре, и её контур знает только она сама. Маска
    # шаблона нужна тут же, вторым слагаемым: под ней лежит СТАРАЯ голова, и
    # если её не накрыть, от прежнего героя останется ободок причёски
    head_new = head_mask.build(aligned, dilate_ratio, feather_ratio, neck_ratio)
    head_old = head_mask.build(template, dilate_ratio, feather_ratio, neck_ratio)
    allowance = _allowance(head_old, feather_ratio)
    # Маска по генерации ограничена окрестностью головы ШАБЛОНА, см. `_allowance`
    mask = np.maximum(np.minimum(head_new.mask, allowance), head_old.mask)

    clipped = int(np.count_nonzero((head_new.mask > 127) & (allowance <= 127)))
    orphan = int(np.count_nonzero((head_old.mask > 127) & (head_new.mask <= 127)))

    meta = {
        "orphan_px": orphan,
        # Сколько маски по генерации срезано ограничением. Ноль означает, что
        # ограничение на этом кадре не работало вовсе, — а не что его нет
        "clipped_px": clipped,
        "plate": plate is not None,
        # Чем меряли масштаб. В мете обязательно: с переносом причёски режим
        # перестаёт быть умолчанием, и глядя на кадр надо знать, каким он был
        "scale_mode": scale_mode or SCALE_MODE,
        "scale": round(scale, 3),
        "angle": round(angle, 1),
        "shift": [round(float(matrix[0, 2]), 1), round(float(matrix[1, 2]), 1)],
        "face_height_template": round(geometry_t["face_height"], 1),
        "face_height_generated": round(geometry_g["face_height"], 1),
        "mask_new_px": int(np.count_nonzero(head_new.mask > 127)),
        "mask_old_px": int(np.count_nonzero(head_old.mask > 127)),
        "mask_px": int(np.count_nonzero(mask > 127)),
    }

    if match_tone:
        aligned, tone = _match_tone(template, aligned, mask)
        meta.update(tone)

    if match_skin:
        # Порядок важен: сперва общий увод по кадру, потом кожа. Наоборот —
        # общая подгонка сдвинула бы уже исправленную кожу заново, и мерка,
        # посчитанная по фону, съела бы мерку, посчитанную по коже
        parsed_t = parsing.parse(template)
        if parsed_t is None:
            meta.update({"skin_matched": False, "skin_reason": "no_parsing"})
        else:
            aligned, skin = _match_skin(
                template, aligned, head_new.mask, parsed_t, geometry_t["face_height"])
            meta.update(skin)

    if plate is None:
        if orphan:
            log.warning(
                "стирание не передано — под старой головой останется содержимое "
                "генерации, на стыке шеи возможно удвоение воротника",
                extra={"orphan_px": orphan},
            )
        result = _paste(template, aligned, mask)
    else:
        if plate.shape != template.shape:
            raise InvalidImageError(
                "Стёртая подложка другого размера, чем шаблон",
                {"plate": list(plate.shape), "template": list(template.shape)},
            )
        # Два действия по очереди, и порядок важен: сперва снимается старая
        # голова, потом на её место садится новая. Вне обеих масок ни один байт
        # не трогается ни на одном из шагов.
        #
        # Стирание идёт по СИЛУЭТУ головы, а не по рабочей маске: та расширена
        # на 29 пикселей, и в этом кольце шаблонный фон цел — отдавать его LaMa
        # значит менять чёткий хребет на размытое пятно. Разметки может не быть,
        # тогда выбора нет и стираем по маске, как раньше
        erase = head_silhouette(template, points_t, geometry_t["face_height"])
        if erase is None:
            log.info("силуэт головы не построен — стираем по рабочей маске")
            erase = head_old.mask
        meta["erase_px"] = int(np.count_nonzero(erase > 127))

        cleared = _paste(template, plate, erase)
        result = _paste(cleared, aligned, head_new.mask)
    meta["changed_px"] = int(np.count_nonzero(np.any(result != template, axis=2)))
    log.info("голова пересажена в шаблон", extra=meta)
    return Transplanted(image=result, meta=meta)


def _match_tone(template: Any, aligned: Any, mask: Any) -> tuple[Any, dict]:
    """
    Приводит тон генерации к шаблону по пикселям вне маски.

    ПОЧЕМУ НЕ НАКЛОН РЕГРЕССИИ. Исходно поправка считалась как `cov/var` — той
    же формулой, что в `composite.py::_match_levels`. Там она верна: путь через
    SDXL возвращает ТОТ ЖЕ кадр, вне маски картинки совпадают почти побитово
    (замер: 2.6 уровня расхождения), и наклон меряет ровно экспозицию.

    В пути через FLUX посылка ложна. Генератор переписывает кадр целиком и
    возвращает СВОЮ сцену: вне маски расхождение 22 уровня, корреляция 0.60-0.91
    вместо почти единицы. Наклон регрессии при неполной корреляции затухает —
    он равен `r * s_шаблона / s_генерации`, — и замер это показал прямо:

        кадр            наклон               корреляция
        dino1_id1       0.941 0.912 0.884    0.914 0.875 0.849
        dino2_id6       0.629 0.647 0.658    0.602 0.604 0.621
        spread_08_id1   0.690 0.743 0.695    0.654 0.672 0.622

    Наклон и корреляция — одно число. Значит, отношение разбросов около единицы
    (замер: 1.03..1.12), контраст у генерации и шаблона практически одинаков, а
    весь «наклон меньше единицы» — снос оценки от несовпадения содержимого.
    Применять его значит сжимать контраст головы на 6-12% беспричинно.

    ЧТО СЧИТАЕТСЯ ВМЕСТО. Поканальная гамма, приводящая СРЕДНЕЕ генерации к
    среднему шаблона. От затухания она свободна по построению: берёт статистику
    каждой картинки по отдельности и не спрашивает, совпадают ли они попиксельно.

    ПОЧЕМУ ГАММА, А НЕ МНОЖИТЕЛЬ СО СДВИГОМ. Множитель проверен живым прогоном и
    отвергнут — ровно как в `_match_skin`, и по той же причине. Отношение
    разбросов вышло больше единицы (1.03..1.12), то есть поправка РАСТЯГИВАЛА
    контраст, а поверх неё идёт гамма кожи. Вместе они съели запас до потолка:
    замер на 21 кадре показал клиппинг кожи до 2.2% там, где раньше был ноль.
    `(c/255)^g` при положительном g остаётся в пределах шкалы при любом g, и
    выбить света в белое не может по построению.

    Цена решения названа прямо: контраст поправка не трогает. Отношение
    разбросов и так около единицы, а 20-30 уровней смещения на разворотах гамма
    берёт целиком — ради чего всё и затевалось.

    КОРРЕЛЯЦИЯ ВСЁ РАВНО НУЖНА — но как условие применимости, а не как оценка.
    Обе мерки предполагают, что вне маски изображена ОДНА И ТА ЖЕ сцена, пусть
    и перерисованная. Упади корреляция совсем низко — модель поменяла
    композицию, и переносить тон неоткуда.
    """
    import numpy as np

    outside = mask <= 8
    if int(np.count_nonzero(outside)) < 64:
        return aligned, {"matched": False}

    gammas, agreement, levels = [], [], []
    for channel in range(template.shape[2]):
        source = aligned[..., channel][outside].astype(np.float64) / 255.0
        target = template[..., channel][outside].astype(np.float64) / 255.0
        source_mean, target_mean = float(source.mean()), float(target.mean())
        levels.append((source_mean, target_mean))

        # Логарифмы берутся от чисел строго внутри (0, 1): на концах гамма не
        # определена, а среднее кадра там означает, что вне маски сплошной
        # чёрный или сплошной белый — и переносить оттуда нечего
        gammas.append(
            float(np.log(np.clip(target_mean, 0.02, 0.98))
                  / np.log(np.clip(source_mean, 0.02, 0.98)))
        )

        variance, spread = float(source.var()), float(target.var())
        if variance * 255.0**2 < _TONE_MIN_VARIANCE or spread * 255.0**2 < _TONE_MIN_VARIANCE:
            # Корреляции здесь НЕТ, а не «она нулевая»: на ровной области её не
            # из чего считать. Разница существенная — нулём канал утащил бы
            # проверку применимости в отказ на ровном небе, где поправка как раз
            # осмысленна и сводится к сдвигу средних
            agreement.append(None)
        else:
            covariance = float(((source - source_mean) * (target - target_mean)).mean())
            agreement.append(covariance / (variance * spread) ** 0.5)

    report = {
        "match_gamma": [round(g, 3) for g in gammas],
        "match_level": [[round(a, 3), round(b, 3)] for a, b in levels],
        "match_r": [None if r is None else round(r, 3) for r in agreement],
    }

    measurable = [r for r in agreement if r is not None]
    if measurable and min(measurable) < _TONE_MIN_AGREEMENT:
        # Сцена перерисована настолько, что общего у картинок не осталось.
        # Переносить тон неоткуда: любые числа здесь описывают две разные
        # картинки, а не увод одной
        return aligned, {"matched": False, "match_reason": "scene_changed", **report}

    if any(not _TONE_GAMMA_MIN <= g <= _TONE_GAMMA_MAX for g in gammas):
        return aligned, {"matched": False, "match_reason": "out_of_range", **report}

    base = aligned.astype(np.float32) / 255.0
    corrected = np.empty_like(base)
    for channel, gamma in enumerate(gammas):
        corrected[..., channel] = np.power(np.clip(base[..., channel], 0.0, 1.0), gamma)
    return np.rint(255.0 * corrected).astype(np.uint8), {"matched": True, **report}


def _match_skin(
    template: Any, aligned: Any, mask: Any, parsed_t: Any, face_height: float
) -> tuple[Any, dict]:
    """
    Приводит тон КОЖИ генерации к тону кожи персонажа шаблона.

    ЗАЧЕМ ОТДЕЛЬНО ОТ `_match_tone`. Та подгонка считается по пикселям ВНЕ
    маски — по небу, горам, жилету и динозавру — и ловит общий увод экспозиции.
    К коже она отношения не имеет, и замер это показал: на стыке шеи светлота
    кожи прыгает на 14.5 L* (dino1_id4) и на 24 L* (dino1_id6), тогда как у
    самого шаблона кожа в тех же кольцах ровная, 34±2 L*. То есть весь разрыв
    внесён вклейкой, и виден он как резкая граница поперёк шеи: светлый
    подбородок нового ребёнка над смуглой шеей прежнего героя.

    ПОЧЕМУ ДВИГАЕМ ГЕНЕРАЦИЮ, А НЕ ШАБЛОН. Обратный ход — подкрасить шею и грудь
    персонажа под донора — ломает главное обещание пайплайна: вне маски шаблон
    доходит до печати побитово. Вдобавок красить пришлось бы всю видимую кожу
    разворота, иначе шея сойдётся, а руки нет. Цена принятого решения названа
    прямо: ребёнок получает тон кожи персонажа, а не свой.

    ГДЕ МЕРЯЕТСЯ. В кольце ВНУТРИ маски, у самой границы вклейки, и только на
    нижней её части — то есть на шее, а не на темени. Донор сравнивается с
    ПРЕЖНИМ ГЕРОЕМ в том же самом кольце: под маской ещё лежит его кожа, и это
    единственная пара замеров, у которой совпадают и место, и поза, и свет.

    Сравнивать через границу — донора внутри с шаблоном снаружи — пробовали, и
    так делать нельзя. Между подбородком и шеей есть законный перепад: одно
    освещено, другое в тени. Правка, загоняющая этот перепад в ноль, на dino1
    сработала (там он и был около нуля), а на spread_08, где голова занимает
    седьмую часть кадра и перепад доходит до 8.6 L*, перевернула ступень с +0.4
    на −6.3 — то есть починила кадр, который не был сломан. Замер внутри кольца
    от этой ошибки свободен по построению: сравниваются две кожи в одной точке
    сцены, и естественный перепад сокращается.

    ЧЕМ ПРАВИТСЯ. Светлота — гаммой, цветность — сдвигом. Не сдвигом по
    светлоте, потому что тень на шее обязана остаться тенью: сдвиг поднял бы её
    вместе со светами и сплющил объём.

    И не множителем — он проверен живым прогоном и отвергнут. Пока донор светлее
    персонажа, множитель меньше единицы и всё хорошо; но донор бывает и смуглее,
    тогда множитель больше единицы, и света упираются в потолок. Замер на
    перегоне: при 1.319 и 1.465 в белое выбило 20% и 16% пикселей кожи — лицо
    сгорело. Гамма от этого свободна по построению: она оставляет на месте и 0,
    и 100, а медиану приводит куда нужно. Проверить это на 21 старом кадре было
    нельзя — там все доноры оказались светлее шаблона, и множитель ни разу не
    вышел за единицу.

    :param parsed_t: разметка ШАБЛОНА, уже посчитанная вызывающим
    :param face_height: высота лица персонажа, база всех долей в модуле
    :return: поправленная генерация и отчёт
    """
    import cv2
    import numpy as np

    skin_t = np.asarray(parsed_t.bare_skin) > 127
    parsed_g = parsing.parse(aligned)
    if parsed_g is None:
        return aligned, {"skin_matched": False, "skin_reason": "no_parsing"}
    skin_g = np.asarray(parsed_g.bare_skin) > 127

    inside = mask >= 250
    if not inside.any():
        return aligned, {"skin_matched": False, "skin_reason": "no_mask"}

    ring = max(2, int(round(face_height * _SKIN_RING_RATIO)))
    kernel = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * ring + 1,) * 2)
    near_in = (cv2.erode(inside.astype(np.uint8), kernel) == 0) & inside

    # Только низ маски: там шея, и там же виден дефект
    rows = np.nonzero(inside)[0]
    low = np.zeros(mask.shape, bool)
    low[int(np.percentile(rows, _SKIN_LOW_PERCENTILE)):] = True

    # Набор пикселей ОДИН на оба замера: кожа и у донора, и у прежнего героя.
    # Считать медианы по своим наборам нельзя, и это проверено — разметка
    # обводит кожу по-разному на двух картинках, один набор попадает на
    # освещённую челюсть, другой на затенённую шею, и разница наборов уезжает в
    # поправку как разница тона. На замере такая мерка тянула вниз лишние
    # 3-7 L* на dino2 и spread_08.
    both = near_in & skin_g & skin_t & low
    if int(both.sum()) < _SKIN_MIN_PX:
        return aligned, {
            "skin_matched": False, "skin_reason": "no_skin",
            "skin_px": int(both.sum()),
        }

    base = aligned.astype(np.float32) / 255.0
    src = np.median(base[both], axis=0)
    dst = np.median(template.astype(np.float32)[both] / 255.0, axis=0)

    # Гамма СВОЯ на каждый канал. Так поправка попадает в медиану персонажа по
    # всем трём сразу, то есть заодно делает то, ради чего раньше стоял
    # отдельный сдвиг цветности, — и делает надёжнее: сдвиг мог вытолкнуть
    # пиксель за край шкалы, а гамма не может, потому что (c/255)^g при любом
    # положительном g остаётся в тех же пределах.
    #
    # Логарифмы берутся от чисел строго внутри (0, 1): на самих концах гамма не
    # определена, а кожа там означает, что мерка попала на пересвет или в тень
    gamma = np.clip(
        np.log(np.clip(dst, 0.02, 0.98)) / np.log(np.clip(src, 0.02, 0.98)),
        _SKIN_GAMMA_MIN, _SKIN_GAMMA_MAX,
    ).astype(np.float32)

    # Правим только кожу: гамма на волосах перекрасила бы причёску заодно.
    # Переход мягкий — граница кожи и волос реальная, и резкая ступень по ней
    # была бы видна не меньше исходного дефекта
    weight = cv2.GaussianBlur(skin_g.astype(np.float32), (0, 0), max(1.0, ring / 2.0))
    corrected = np.power(np.clip(base, 0.0, 1.0), gamma)

    result = np.rint(
        255.0 * (base + weight[..., None] * (corrected - base))
    ).astype(np.uint8)
    # Где кожи нет, не должно остаться и следа поправки: округление не должно
    # решать, а вклейка обязана получить генерацию нетронутой
    result[weight <= 0.0] = aligned[weight <= 0.0]
    return result, {
        "skin_matched": True,
        "skin_px": int(both.sum()),
        # Светлота в единицах L*, а не в байтах: 100 против 255, и путать их
        # при чтении лога дороже, чем поделить здесь
        # Медианы кожи, доли шкалы: слева донор, справа персонаж шаблона
        "skin_donor": [round(float(v), 3) for v in src],
        "skin_host": [round(float(v), 3) for v in dst],
        "skin_gamma": [round(float(v), 3) for v in gamma],
    }


def _paste(template: Any, aligned: Any, mask: Any) -> Any:
    """
    Вклейка по растушёванной маске с побитовым возвратом шаблона снаружи.

    Растушёвка уже заложена в саму маску (`feather_ratio`), поэтому здесь только
    веса. Обещание «вне маски не тронут ни один пиксель» держится не арифметикой
    с нулевым весом, а явным копированием: округление не должно решать.
    """
    import numpy as np

    alpha = (mask.astype(np.float32) / 255.0)[..., None]
    blended = np.rint(
        template.astype(np.float32) * (1.0 - alpha) + aligned.astype(np.float32) * alpha
    ).astype(np.uint8)
    untouched = mask == 0
    blended[untouched] = template[untouched]
    return blended
