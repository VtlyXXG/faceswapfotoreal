"""
Стратегия «проброс лицевых эмбеддингов»: контракт есть, реализации нет.

Второй способ решать ту же задачу. Личность передаётся эндпоинту не пикселями,
а вектором — матрицей эмбеддингов вида Nx512, какую отдаёт InsightFace, — и
лицо рисуется по этому вектору с нуля. Коллаж тогда нужен лишь как композиция:
поза, кадрирование, причёска.

Почему заглушка, а не реализация. Связки «identity-модель + инпейнтинг по
маске» на fal сейчас нет: flux-pulid и ip-adapter-face-id — чистый
text-to-image, они не принимают ни базового изображения, ни mask_url, то есть
перерисовывают весь кадр целиком. Отдать им разворот означает потерять всю
живопись вокруг головы. Отдельно нечем и считать сами эмбеддинги: InsightFace
тянет onnxruntime и свои веса, а от локального инференса в этом сервисе
уходили осознанно.

Что нужно сделать, когда эндпоинт появится:

  1. посчитать эмбеддинги — локально (InsightFace) или облачным вызовом — и
     сложить в `RefineRequest.identity` вместе с именем модели: векторы разных
     детекторов лежат в разных пространствах и несравнимы;
  2. сериализовать матрицу так, как ждёт эндпоинт (обычно JSON-список float
     либо загруженный .npy), — имя ключа положить в профиль, как control_field;
  3. решить, что делать с маской: если эндпоинт её принимает, работает прежняя
     защита лица; если нет — вокруг головы придётся собирать кадр самим.

До тех пор честнее отказать явным 501, чем молча отработать инпейнтингом:
молчаливая подмена стратегии обнаружилась бы уже на печати тиража.
"""

from __future__ import annotations

from app.pipelines.refine.base import (
    RefineRequest,
    RefineResult,
    RefinerNotSupportedError,
    register,
)
from app.pipelines.refine.profiles import RefineProfile


class IdentityEmbeddingRefiner:
    """Проброс матрицы лицевых эмбеддингов в эндпоинт. Не реализовано."""

    name = "identity_embedding"

    def refine(self, request: RefineRequest, profile: RefineProfile) -> RefineResult:
        raise RefinerNotSupportedError(
            "Проброс лицевых эмбеддингов пока не реализован: на fal нет эндпоинта, "
            "который принимает identity-вектор вместе с базовым кадром и маской",
            {
                "strategy": self.name,
                "endpoint": profile.endpoint,
                # Видно, дошли ли эмбеддинги до стратегии: когда появится
                # эндпоинт, первым вопросом будет именно этот
                "identity_present": request.identity is not None,
            },
        )


register(IdentityEmbeddingRefiner())
