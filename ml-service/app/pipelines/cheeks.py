"""
Разрушение структуры старой пряди В ПОЛОСЕ ВДОЛЬ ЩЕКИ, до отправки редактору.

Отличие от `erase.py` — в том, ЧЕМ задана область и что остаётся после работы.
Стирание брало всю маску волос и заливало её по окружению; прогон показал, что
так теряется силуэт причёски (редактор рисует ёжик по черепу) и появляется
светлый ореол по границе заливки. Здесь область — только полоса щеки
(`hair_mask._cheek_bands`), макушка не трогается вовсе, а вместо заливки
по окружению берётся измеренный тон КОЖИ.

Зачем это нужно после того, как полоса заработала. Полоса открывает прядь в
маске, но открытая маска — это разрешение рисовать, а не приказ. Редактор не
рисует область с нуля, он переписывает присланные пиксели, и тёмная контрастная
линия на светлой щеке читается им как тень скулы или край челюсти — то есть как
анатомия лица, которую тот же промпт трогать запрещает. Слова против пикселей
проигрывают. Значит, менять надо пиксели: там, где мы объявили область
причёской, у старой пряди не должно остаться ни контраста, ни контура.

Чем это НЕ является. Ни один изуродованный пиксель не может попасть в готовый
разворот, и держится это не на аккуратности, а на построении: альфа умножается
на финальную маску волос, а вклейка (`composite.paste`) берёт всё, что вне
маски, из НЕТРОНУТОГО кадра. Отсюда же бесплатная защита глаз, носа и рта — из
маски ядро лица уже вычтено, и заливке до него не дотянуться при любой ошибке
геометрии.

Четыре опасности, из-за которых модуль устроен сложнее, чем «залить и размыть».

  1. **Отравленный сэмпл.** Тон кожи меряется рядом с полосой, и если прядь
     заходит медиальнее её кромки, диск сэмплирования читает саму прядь:
     медиана уезжает в тёмное, полоса заливается тёмным — то есть ровно тем
     артефактом, который мы удаляем, и заметить это изнутри нечем. Поэтому
     сэмпл берётся только там, где разметка говорит FACE, и никогда — внутри
     полосы. Фильтр не теоретический: прогон стирания доказал, что такую прядь
     разметка не относит ни к волосам, ни к лицу, и класс FACE её исключает.
  2. **Экстраполированные лендмарки.** MediaPipe всегда отдаёт все 468 точек и
     не сообщает, какие из них ушли за силуэт. На сильном развороте дальняя
     тройка оказывается на фоне, ухе или волосах, и «медианой кожи» стало бы
     небо. Тот же фильтр по классу FACE ловит и это: мало валидных пикселей —
     сторона недостоверна, тон берётся с противоположной, а если недостоверны
     обе, работа не делается вовсе.
  3. **Жёсткий край.** Полоса — прямоугольник, и бинарная альфа поставила бы
     поперёк щеки, челюсти и воротника идеально прямую контрастную линию, для
     редактора куда более осмысленную, чем удаляемая прядь. Это уже наблюдалось
     живьём как светлый ореол по границе стирания. Альфа растушёвывается.
  4. **Тон кожи на небе — и низкочастотный призрак вместо него.** Полоса уходит
     наружу до 1.8 полуширины лица, то есть заметно дальше силуэта головы:
     изрядная её часть — фон, воротник и сама старая копна. Залить их цветом
     щеки значит поставить внутри маски пятно чужого тона, а такое пятно
     переживает вклейку и читается как ореол.

     Первым решением была одна зона: заливка только по голой коже, всё
     остальное — размытие. Прогон показал цену такой осторожности, и она
     оказалась выше выигрыша. Тёмные пиксели пряди над фоном никуда не
     девались: размытие превращало резкую прядь в МЯГКОЕ ТЁМНОЕ ПЯТНО, и
     редактор читал его как тень заднего плана — то есть как часть сцены,
     которую положено сохранить. На ракурсах в три четверти, где дальняя щека
     уходит из-под класса кожи, грязное пятно оставалось на каждом прогоне.

     Отсюда две зоны и два тона. По коже льётся медиана кожи, по фону — медиана
     ФОНА, замеренная рядом с полосой. Тёмный пиксель не размывается, а
     перезаписывается цветом того, над чем он висит; блюр после этого смешивает
     плоскую кожу с плоским небом, и чёрного не остаётся нигде.

     Двух исключений это не отменяет. Класс волос заливкой не трогается — это
     силуэт старой копны, единственное указание редактору, где растут волосы
     (стирание, снёсшее его, дало ёжик по черепу). Одежда тоже: цвет неба на
     вороте — то же чужое пятно внутри маски. Обе остаются на размытии.
  5. **Тон щеки на шее — и хвост причёски, выведенный из-под удара.** Шея тоже
     кожа, и в зону заливки она проходит по классу разметки на общих правах. Но
     освещена она иначе: под подбородком лежит его собственная тень, и лицевая
     медиана ставит там светлое пятно — внутри маски, то есть переживающее
     вклейку. Заливка тоном КОЖИ поэтому обрезается по нижнему контуру челюсти
     (`head_mask.jaw_line`). Полосу это не укорачивает: маска доходит до
     воротника, где кончается прядь, как и раньше.

     У отсечки нашлось побочное действие, и стоило оно грязи на композите. Класс
     волос исключён из обеих заливок — это силуэт копны, единственное указание
     редактору, где растут волосы. Но НИЖЕ ЧЕЛЮСТИ никакого силуэта уже нет:
     там висит хвост, который мы как раз срезаем. Он не попадал ни в одну зону
     и получал только размытие — на профильных кадрах с густой причёской под
     ухом оставались тёмные пряди.

     Отсюда прорыв: ниже линии челюсти класс волос присоединяется к ФОНОВОЙ
     зоне и заливается её тоном. Строго вниз и строго по волосам; голая кожа шеи
     и одежда исключены явно — тон фона на шее или на вороте был бы тем же чужим
     пятном, от которого мы ушли двухтоновой заливкой. Выше челюсти класс волос
     по-прежнему неприкосновенен.

Сколько частот разрушать — ручка `flat_ratio`. Единица означает буквально
плоскую заливку: структуры не остаётся никакой, но вместе с ней уходит и
низкочастотный градиент щеки — свет сцены и объём. Меньше единицы — тон тянется
к чистой коже, а градиент выживает; платой становится мягкое тёмное пятно на
месте пряди, то есть частичный возврат исходного дефекта. Крайности
воспроизводятся одной переменной окружения, спорить о них не нужно.
"""

from __future__ import annotations

from typing import Any

from app.core.logging import get_logger
