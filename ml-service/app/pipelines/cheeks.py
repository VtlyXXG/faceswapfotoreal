log = get_logger(__name__)

# Тройки лендмарок MediaPipe на щеке, по одной на сторону. Индексация у сетки
# СУБЪЕКТНАЯ: «левая» — собственная левая щека персонажа, на неотзеркаленном
# кадре она справа. Поэтому имена здесь ни на что не влияют — сторона полосы
# определяется знаком проекции на поперечную ось, см. `_lateral`
_OWN_LEFT = (50, 117, 205)
_OWN_RIGHT = (280, 346, 425)

# Насколько диск сэмплирования отступает от кромки полосы, в его же радиусах.
# Единицы мало: у диска и у кромки свои погрешности округления, и вплотную он
# цепляет первый ряд пикселей полосы.
_SAMPLE_CLEARANCE = 1.2

# Куда диск не сдвигается ни при каких обстоятельствах, доли высоты лица от оси.
# Ближе начинается крыло носа, и тон оттуда — уже не тон щеки.
_SAMPLE_FLOOR_RATIO = 0.18

# Радиус диска сэмплирования, доля высоты лица. Доля, а не пиксели: тот же
# модуль работает и по 4K-развороту, и по кропу, а всё остальное в маске волос
# отмеряется от высоты лица
_SAMPLE_RATIO = 0.05

# Сколько пикселей класса FACE должно остаться в диске после фильтрации, чтобы
# медиане можно было верить. Ниже порога сторона объявляется недостоверной —
# это и есть ловушка на лендмарки, уехавшие за силуэт при развороте головы
_MIN_SAMPLE_PX = 24

# Растушёвка альфы, доля высоты лица. Против прямой линии поперёк щеки: край
# заливки не должен становиться структурой сильнее той, что мы разрушаем
_FEATHER_RATIO = 0.03

# Насколько раздуть маску голой кожи, прежде чем разрешить внутри неё заливку
# замеренным тоном, доля высоты лица. Раздувается затем, что прядь коже НЕ
# принадлежит: разметка не относит её ни к одному классу, и в маске кожи она —
# дыра ровно по своей форме. Замыкание этой дыры и есть смысл поля: без него
# заливка обошла бы прядь стороной, оставив её нетронутой
_SKIN_REACH_RATIO = 0.08

# Запас вокруг полосы, в сигмах: блюру нужен контекст за границей области,
# иначе у кромки ROI он потянет тон из ничего
_ROI_SIGMAS = 3.0

# Насколько расширить рамку полосы, чтобы намерить в ней тон ФОНА, доли высоты
# лица. Мерить надо снаружи полосы: внутри неё лежит прядь, и, прочитав её, мы
# залили бы её собственным цветом.
_BACKGROUND_MARGIN_RATIO = 0.35

# Предел выборки для запасной медианы фона по всему кадру. Медиана по четырём
# миллионам точек стоит заметно дороже, чем отличается от медианы по двумстам
# тысячам, а путь этот и так запасной.
_GLOBAL_SAMPLE_PX = 200_000


def _structure(gray: Any, inside: Any) -> float:
    """
    Сколько структуры в области: средний модуль лапласиана, уровни 0..255.

    Единственный способ узнать, сработало ли разрушение, не разглядывая картинки
    после GPU-часа. Число уезжает в мету до и после: упало на порядок — цепляться
    редактору не за что; осталось прежним — сигма мала для этого кадра либо
    полоса не накрыла прядь, и тогда крутить надо `cheek_ratio`, а не сигму.
    """
    import cv2
    import numpy as np

    if not inside.any():
        return 0.0

    return float(np.abs(cv2.Laplacian(gray, cv2.CV_32F))[inside].mean())


def _lateral(point: Any, geometry: dict) -> float:
    """
    Координата точки поперёк лица: проекция на ось `side`, пиксели со знаком.

    Ею определяется, какой из двух полос принадлежит замеренный тон. Номер
    итерации в `_cheek_bands` для этого не годится: обе полосы пишутся в один
    массив, меток сторон в нём нет, а «левое — это меньший x» ломается на первой
    же голове, склонённой набок. Промах здесь бесшумный — на ровном свете
    медианы двух щёк почти совпадают, и подмена вылезет только на боковом.
    """
    import numpy as np

    return float(np.dot(np.asarray(point, dtype=np.float64) - geometry["chin"], geometry["side"]))


def _median(image: Any, sample: Any) -> tuple[Any | None, int]:
    """
    Медианный BGR по булевой выборке. None — пикселей мало, верить нечему.

    Медиана по каналу отдельно: строгую медиану цвета считать не за чем, нужна
    устойчивость к выбросам, а не корректность в цветовом пространстве.
    """
    import numpy as np

    count = int(np.count_nonzero(sample))
    if count < _MIN_SAMPLE_PX:
        return None, count
    return np.median(image[sample].astype(np.float32), axis=0), count


def _scene(parsed: Any) -> Any:
    """
    Где НЕ персонаж: ни лицо, ни волосы, ни кожа тела, ни одежда.

    Сюда же попадает та самая прядь, ради которой всё написано: сегментатор не
    относит её ни к одному классу, и в дополнении она оказывается вместе с
    небом. Это не помеха, а свойство: заливая «фон», мы заливаем и её.
    """
    import numpy as np

    def flat(layer: Any) -> Any:
        array = np.asarray(layer)
        return (array[..., 0] if array.ndim == 3 else array) > 127

    return ~(flat(parsed.face) | flat(parsed.hair) | flat(parsed.skin) | flat(parsed.clothes))


def _background(
    image: Any, scene: Any, bands: Any, geometry: dict, margin: int
) -> tuple[Any | None, Any | None, list[int]]:
    """
    Медианный цвет фона по сторонам полосы. (положительная, отрицательная, счёт).

    Зона сэмплирования — расширенная рамка полосы за вычетом самой полосы: тон
    берётся из окружения, а не из области, которую мы собираемся переписать.
    Причина та же, что у тона кожи: прочитав прядь, мы залили бы её собственным
    цветом и получили ровно тот артефакт, который удаляем.

    Стороны разделяются знаком проекции на поперечную ось — той же арифметикой,
    что и всё остальное здесь. Небо слева и справа от головы бывает разным: у
    персонажа на фоне леса с одной стороны просвет, с другой ствол.
    """
    import numpy as np

    rows, columns = np.nonzero(bands)
    if not rows.size:
        return None, None, [0, 0]

    height, width = image.shape[:2]
    top = max(0, int(rows.min()) - margin)
    bottom = min(height, int(rows.max()) + 1 + margin)
    x0 = max(0, int(columns.min()) - margin)
    x1 = min(width, int(columns.max()) + 1 + margin)

    zone = np.zeros(image.shape[:2], dtype=bool)
    zone[top:bottom, x0:x1] = True
    zone &= scene & ~(bands > 0)

    sample_rows, sample_columns = np.nonzero(zone)
    if not sample_rows.size:
        return None, None, [0, 0]

    chin, side = geometry["chin"], geometry["side"]
    lateral = (sample_columns - chin[0]) * side[0] + (sample_rows - chin[1]) * side[1]
    pixels = image[sample_rows, sample_columns].astype(np.float32)

    counts = []
    tones: list[Any | None] = []
    for positive in (True, False):
        chosen = pixels[lateral >= 0] if positive else pixels[lateral < 0]
        counts.append(int(chosen.shape[0]))
        tones.append(np.median(chosen, axis=0) if chosen.shape[0] >= _MIN_SAMPLE_PX else None)

    return tones[0], tones[1], counts


def _global_background(image: Any, scene: Any) -> Any | None:
    """
    Медианный цвет фона по всему кадру — запасной путь.

    Нужен на краевом случае: полоса упёрлась в край разворота либо её окружение
    целиком занято персонажем, и чистых пикселей фона рядом не нашлось. Считается
    по прореженной выборке: медиана по четырём миллионам точек стоит заметно
    дороже, чем отличается от медианы по двумстам тысячам.
    """
    import numpy as np

    rows, columns = np.nonzero(scene)
    if rows.size < _MIN_SAMPLE_PX:
        return None

    step = max(1, rows.size // _GLOBAL_SAMPLE_PX)
    return np.median(image[rows[::step], columns[::step]].astype(np.float32), axis=0)


def _band_edges(bands: Any, geometry: dict) -> tuple[float, float]:
    """
    Внутренние кромки полос по сторонам, пиксели от оси. (плюс, минус).

    Спрашивается у самого массива, а не берётся константой из `hair_mask`: там
    кромка считается тремя разными способами и однажды уже переезжала. Одно
    измерение по факту надёжнее трёх согласованных предположений.
    """
    import numpy as np

    rows, columns = np.nonzero(bands)
    if not rows.size:
        return float("inf"), float("inf")

    chin, side = geometry["chin"], geometry["side"]
    lateral = (columns - chin[0]) * side[0] + (rows - chin[1]) * side[1]

    positive = lateral[lateral >= 0]
    negative = lateral[lateral < 0]
    return (
        float(positive.min()) if positive.size else float("inf"),
        float(-negative.max()) if negative.size else float("inf"),
    )


def _pull_inside(
    centroid: Any, geometry: dict, edges: tuple[float, float], radius: int, face_height: float
) -> Any:
    """
    Сдвигает центр диска к оси, пока он не выйдет из-под полосы.

    Без этого сэмпл ломается ровно тогда, когда полоса становится агрессивной.
    Опорные точки щеки лежат около 0.70 полуширины, и пока кромка стояла на
    0.75, диск попадал в чистую кожу медиальнее неё. Стоило опустить кромку на
    висок (0.55, против корня пряди у глаза) — и диск целиком оказался ВНУТРИ
    полосы, где читать тон запрещено; выборка обнулилась, и весь шаг молча
    выключился с причиной `no_tone`.

    Сдвиг идёт строго поперёк, вдоль оси положение сохраняется: это та же щека,
    только ближе к носу. Ниже пола не опускаемся — там уже крыло носа, а не
    щека, — и если места не осталось вовсе, решает порог `_MIN_SAMPLE_PX`.
    """
    import numpy as np

    chin, side, up = geometry["chin"], geometry["side"], geometry["up"]
    offset = np.asarray(centroid, dtype=np.float64) - chin
    lateral = float(np.dot(offset, side))
    along = float(np.dot(offset, up))

    edge = edges[0] if lateral >= 0 else edges[1]
    limit = max(face_height * _SAMPLE_FLOOR_RATIO, edge - radius * _SAMPLE_CLEARANCE)
    if abs(lateral) <= limit:
        return centroid

    return chin + up * along + side * (np.sign(lateral) * limit)


def _tone(image: Any, centroid: Any, radius: int, allowed: Any) -> tuple[Any | None, int]:
    """
    Медианный BGR кожи в диске вокруг центроида. None — сэмплу верить нельзя.

    :param allowed: где вообще разрешено читать пиксели: класс FACE за вычетом
        самой полосы. Без этой маски диск может лечь на прядь (тогда мы зальём
        полосу её же цветом) или на фон (тогда — цветом неба)
    :return: медиана и число пикселей, по которым она посчитана. Второе уезжает
        в мету: это и есть мера доверия к первому
    """
    import cv2
    import numpy as np

    disc = np.zeros(image.shape[:2], dtype=np.uint8)
    # Центроид может оказаться и за пределами кадра — на сильном развороте
    # лендмарки экстраполируются наружу. cv2 такой круг просто обрежет, а
    # порог по числу пикселей поймает то, что от него осталось
    cv2.circle(disc, (int(round(centroid[0])), int(round(centroid[1]))), radius, 1, -1)

    return _median(image, (disc > 0) & allowed)


def flatten(image: Any, hair: Any, wipe_ratio: float, flat_ratio: float) -> tuple[Any, dict]:
    """
    Копия кадра, в которой под полосой щеки не осталось структуры старой пряди.

    Работает по ПОЛНОМУ кадру, а не по окну редактора, и это не расточительство:
    геометрия лица и полоса посчитаны в координатах разворота, а окно вырезается
    позже. Считать здесь в координатах окна значило бы вычитать (left, top)
    руками — молчаливый промах на тысячу пикселей ценой одной забытой правки.
    Блюр при этом идёт только по ROI вокруг полосы, так что размер разворота в
    цену почти не входит.

    :param image: разворот-шаблон, BGR numpy.ndarray
    :param hair: `hair_mask.HairMask` — маска, полоса, разметка кожи, лендмарки
        и геометрия. Всё, кроме маски, может быть None: разворот без сетки лица
        строится по разметке, и тогда шести опорных точек не существует
    :param wipe_ratio: сигма размытия, доля высоты лица. 0 выключает работу
        целиком и возвращает тот же объект. Ориентир — порядок ширины пряди:
        сигма меньше неё оставит её отчётливой тёмной полосой
    :param flat_ratio: вес плоской заливки против размытого оригинала, 0..1.
        1 — заливка целиком: структуры не остаётся, но исчезает и градиент щеки
    :return: кадр и отчёт. `flattened=False` означает «кадр не тронут», и рядом
        лежит причина: выключено, полосы нет, сетки лица нет, полосу съела
        защита или тону нельзя верить ни с одной стороны
    """
    import cv2
    import numpy as np

    if wipe_ratio <= 0:
        return image, {"flattened": False, "reason": "off"}

    if hair.cheeks is None:
        # Полоса выключена (`cheek_ratio=0`) — разрушать нечего и негде
        return image, {"flattened": False, "reason": "no_bands"}

    if hair.points is None or hair.geometry is None:
        # Путь без сетки лица: маска построена по разметке, шести опорных точек
        # не существует, мерить тон нечем. Отказ, а не догадка наугад
        log.info("полоса щеки не разрушена: сетки лица нет, тон кожи мерить нечем")
        return image, {"flattened": False, "reason": "no_landmarks"}

    if len(hair.points) <= max(_OWN_LEFT + _OWN_RIGHT):
        return image, {"flattened": False, "reason": "short_mesh"}

    mask = hair.mask
    if mask.ndim == 3:
        mask = mask[..., 0]

    bands = hair.cheeks > 127
    # Разрушение идёт только там, где редактору и так разрешено рисовать. Отсюда
    # два свойства сразу: испорченный пиксель не может пережить вклейку (вне
    # маски она берёт кадр нетронутым), и ядро лица неприкосновенно — из маски
    # оно уже вычтено, так что до глаз, носа и рта заливка не достанет никогда
    open_bands = bands & (mask > 0)
    if not open_bands.any():
        log.info("полоса щеки не разрушена: до маски она не дошла")
        return image, {"flattened": False, "reason": "closed"}

    # Где разрешено ЧИТАТЬ тон. Внутри полосы — никогда: там лежит то, что мы
    # собираемся уничтожить, и брать оттуда цвет значит замкнуть петлю
    allowed = ~bands
    face_height = float(hair.face_height)

    # Где разрешено ЗАЛИВАТЬ замеренным тоном: голая кожа — лицо и шея, —
    # раздутая на ширину пряди. Всё остальное из заливки исключено осознанно:
    # на фоне тон щеки стал бы чужим пятном внутри маски, то есть ореолом,
    # пережившим вклейку; на одежде — тем же пятном по вороту; а класс волос
    # трогать заливкой нельзя тем более, это силуэт старой копны, и он у
    # редактора единственное указание, где вообще растут волосы. Там, где
    # заливки нет, остаётся размытие: структуру оно снимает, тон не трогает
    skin_zone = back_zone = None
    hair_class = clothes_class = None
    back_positive = back_negative = None
    back_px = [0, 0]

    if hair.parsed is not None:
        skin = np.asarray(hair.parsed.face)
        if skin.ndim == 3:
            skin = skin[..., 0]
        allowed &= skin > 127

        bare = np.asarray(hair.parsed.bare_skin)
        if bare.ndim == 3:
            bare = bare[..., 0]
        reach = max(1, int(round(face_height * _SKIN_REACH_RATIO)))
        skin_zone = cv2.dilate(
            (bare > 127).astype(np.uint8),
            cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (2 * reach + 1,) * 2),
        )

        # Вторая зона и второй тон. Раньше здесь не было ничего: за пределами
        # кожи оставалось одно размытие — «тон сцены не трогаем». Прогон показал
        # цену такой осторожности: тёмные пиксели пряди над фоном никуда не
        # девались, размытие превращало их в мягкое тёмное пятно, и редактор
        # читал его как тень на заднем плане. Уничтожается структура, а не
        # только резкость, поэтому фон надо ПЕРЕЗАПИСЫВАТЬ — своим же цветом
        scene = _scene(hair.parsed)
        back_zone = (scene & (skin_zone == 0)).astype(np.uint8)

        # Классы волос и одежды нужны ниже, для прорыва под челюсть: там
        # заливка идёт по силуэту старых волос и обязана обойти шею и ворот
        hair_class = np.asarray(hair.parsed.hair)
        hair_class = (hair_class[..., 0] if hair_class.ndim == 3 else hair_class) > 127
        clothes_class = np.asarray(hair.parsed.clothes)
        clothes_class = (clothes_class[..., 0] if clothes_class.ndim == 3 else clothes_class) > 127

        margin = max(1, int(round(face_height * _BACKGROUND_MARGIN_RATIO)))
        back_positive, back_negative, back_px = _background(
            image, scene, bands, hair.geometry, margin
        )

        spare = _global_background(image, scene)
        if back_positive is None:
            back_positive = spare
        if back_negative is None:
            back_negative = spare
        if back_positive is None or back_negative is None:
            # Фона в кадре нет вовсе — персонаж занял его целиком. Заливать
            # нечем, и вторая зона выключается: остаётся прежнее поведение
            log.warning("чистого фона в кадре не нашлось — вторая зона выключена")
            back_zone = None
    else:
        # Без разметки нечем ни защитить сэмпл, ни отличить щеку от неба.
        # Работа делается, но вслепую, и в логе это должно быть видно
        log.warning("полоса щеки разрушается без разметки: сэмпл и заливка идут вслепую")

    radius = max(3, int(round(face_height * _SAMPLE_RATIO)))
    geometry = hair.geometry
    edges = _band_edges(bands, geometry)

    tones: dict[str, dict] = {}
    for name, indices in (("own_left", _OWN_LEFT), ("own_right", _OWN_RIGHT)):
        centroid = np.mean(
            np.asarray([hair.points[index] for index in indices], dtype=np.float64), axis=0
        )
        centroid = _pull_inside(centroid, geometry, edges, radius, face_height)
        tone, count = _tone(image, centroid, radius, allowed)
        tones[name] = {
            "tone": tone,
            "px": count,
            "lateral": _lateral(centroid, geometry),
        }

    left, right = tones["own_left"], tones["own_right"]
    if left["tone"] is None and right["tone"] is None:
        # Обе тройки читают не кожу. Так выглядит либо разворот, при котором
        # щёки ушли за силуэт, либо промах разметки. Догадка тут дороже отказа
        log.warning(
            "полоса щеки не разрушена: тону кожи нельзя верить ни с одной стороны",
            extra={"left_px": left["px"], "right_px": right["px"], "floor": _MIN_SAMPLE_PX},
        )
        return image, {
            "flattened": False,
            "reason": "no_tone",
            "sample_px": [left["px"], right["px"]],
        }

    # Стороны различаются знаком проекции на поперечную ось, а не порядком в
    # коде. Если обе тройки спроецировались одинаково, стороны схлопнулись
    # разворотом — тогда обе полосы заливаются одним тоном, и это честнее, чем
    # раскладывать два цвета по прямоугольникам наугад
    collapsed = (left["lateral"] >= 0) == (right["lateral"] >= 0)
    pooled = [entry["tone"] for entry in (left, right) if entry["tone"] is not None]
    fallback = np.mean(np.asarray(pooled, dtype=np.float32), axis=0)

    if collapsed:
        tone_positive = tone_negative = fallback
    else:
        positive = left if left["lateral"] >= 0 else right
        negative = right if left["lateral"] >= 0 else left
        # Недостоверная сторона берёт тон у противоположной: свет там другой, но
        # кожа та же, и это на порядок ближе к правде, чем фон или прядь
        tone_positive = positive["tone"] if positive["tone"] is not None else fallback
        tone_negative = negative["tone"] if negative["tone"] is not None else fallback

    sigma = max(0.5, face_height * wipe_ratio)
    feather = max(0.5, face_height * _FEATHER_RATIO)

    # ROI с запасом на обе свёртки: у самой кромки окна блюр иначе потянет тон
    # из края массива, и на границе ROI появится своя структура
    rows, columns = np.nonzero(bands)
    pad = int(round(_ROI_SIGMAS * (sigma + feather))) + 2
    height, width = image.shape[:2]
    top = max(0, int(rows.min()) - pad)
    bottom = min(height, int(rows.max()) + 1 + pad)
    x0 = max(0, int(columns.min()) - pad)
    x1 = min(width, int(columns.max()) + 1 + pad)

    roi = image[top:bottom, x0:x1].astype(np.float32)
    roi_bands = bands[top:bottom, x0:x1]
    roi_mask = mask[top:bottom, x0:x1].astype(np.float32) / 255.0

    # Шаг 1 и 2. Заливка раскладывается по знаку той же поперечной координаты,
    # которой размечены тона: одна арифметика на замер и на заливку — один
    # источник ошибки вместо двух
    grid_y, grid_x = np.mgrid[top:bottom, x0:x1]
    chin, side = geometry["chin"], geometry["side"]
    lateral = (grid_x - chin[0]) * side[0] + (grid_y - chin[1]) * side[1]

    positive = (lateral >= 0)[..., None]
    skin_fill = np.where(positive, tone_positive, tone_negative).astype(np.float32)

    # Шаг 3. Размывается ОРИГИНАЛ, а не заливка: размытие константы — та же
    # константа, и в порядке «залить → размыть → смержить» блюр не делает
    # ничего. Ядро считает OpenCV по сигме; задавать его руками значит
    # промахнуться мимо собственной сигмы
    soft = cv2.GaussianBlur(roi, (0, 0), sigma)

    # Ниже челюсти заливки тоном КОЖИ нет. Шея — тоже кожа, и в зону заливки она
    # попадает классом разметки на общих правах, но освещена иначе: под
    # подбородком лежит его собственная тень. Лицевая медиана ставит там светлое
    # пятно, а лежит оно внутри маски, то есть переживает вклейку.
    #
    # Отсечка гасит ТОЛЬКО тон кожи. Фоновую заливку она не трогает: сбоку от
    # шеи лежит тот же фон и та же прядь, что и выше, и там перезаписывать надо
    jaw = head_mask.jaw_line(hair.points, geometry)
    above_jaw = None
    if jaw is not None:
        anchor, normal = jaw
        above_jaw = ((grid_x - anchor[0]) * normal[0] + (grid_y - anchor[1]) * normal[1]) <= 0

    # Две мягкие зоны вместо одной жёсткой. Каждая растушёвана, иначе граница
    # кожи и фона сама стала бы контуром из двух чужих тонов
    skin_soft = np.ones(roi.shape[:2], dtype=np.float32)
    if skin_zone is not None:
        skin_soft = cv2.GaussianBlur(
            skin_zone[top:bottom, x0:x1].astype(np.float32), (0, 0), feather
        )
    if above_jaw is not None:
        skin_soft = skin_soft * cv2.GaussianBlur(above_jaw.astype(np.float32), (0, 0), feather)

    # Прорыв под челюсть ПО КЛАССУ ВОЛОС. Отсечка по челюсти защищает шею от
    # лицевого тона — и заодно выводила из-под удара длинные пряди, висящие ниже
    # неё: класс волос из обеих заливок исключён (силуэт копны), а ниже челюсти
    # никакого силуэта уже нет, там просто хвост, который мы срезаем. Он и
    # оставался тёмным пятном на профильных кадрах с густой причёской.
    #
    # Расширяемся строго по волосам и строго вниз. Голая кожа шеи и одежда
    # исключены явно: тон фона на шее или на вороте — то же чужое пятно внутри
    # маски, от которого мы ушли двухтоновой заливкой
    neck_hair = None
    if above_jaw is not None and hair_class is not None and back_zone is not None:
        roi_slice = (slice(top, bottom), slice(x0, x1))
        neck_hair = (
            ~above_jaw
            & hair_class[roi_slice]
            & (skin_zone[roi_slice] == 0)
            & ~clothes_class[roi_slice]
        )

    back_soft = np.zeros(roi.shape[:2], dtype=np.float32)
    if back_zone is not None:
        area = back_zone[top:bottom, x0:x1] > 0
        if neck_hair is not None:
            area = area | neck_hair
        back_soft = cv2.GaussianBlur(area.astype(np.float32), (0, 0), feather)

    # Цвет — взвешенная смесь двух тонов, вес — их сумма. На стыке зон это даёт
    # плавный переход от кожи к фону вместо ступеньки; там, где обе зоны пусты
    # (класс волос, одежда), вес нулевой и остаётся чистое размытие: силуэт
    # старой копны и тон воротника трогать нельзя, это уже проверено прогоном
    share = skin_soft + back_soft
    back_fill = (
        skin_fill
        if back_zone is None
        else np.where(positive, back_positive, back_negative).astype(np.float32)
    )
    fill = (skin_fill * skin_soft[..., None] + back_fill * back_soft[..., None]) / np.maximum(
        share, 1e-6
    )[..., None]

    weight = (flat_ratio * np.clip(share, 0.0, 1.0))[..., None]
    flattened = fill * weight + soft * (1.0 - weight)

    # Альфа растушёвана и прижата маской. Бинарный край полосы стал бы прямой
    # линией поперёк щеки, челюсти и воротника — структурой сильнее той, что мы
    # разрушаем, и именно она возвращалась светлым ореолом при стирании
    alpha = cv2.GaussianBlur(roi_bands.astype(np.float32), (0, 0), feather) * roi_mask
    alpha = np.clip(alpha, 0.0, 1.0)[..., None]

    merged = roi * (1.0 - alpha) + flattened * alpha

    # Структура меряется по КОЖЕ под полосой, а не по всей полосе. Вопрос, на
    # который отвечает число, — «осталось ли за что цепляться на щеке»; фон и
    # старая копна в полосу тоже попадают, но там структура сохраняется
    # намеренно, и, попав в ту же среднюю, она забила бы собой ответ.
    #
    # Читать надо ПАДЕНИЕ, а не абсолютное значение. В ноль оно не уйдёт
    # никогда: силуэт головы проходит внутри полосы, и перепад на нём остаётся
    # в средней и до, и после — он и должен остаться, это настоящая граница
    # сцены, а не структура старой пряди
    # Область меряется ровно та, по которой работала заливка, — теперь обе зоны.
    # Один источник правды на вес и на метрику: иначе число отвечало бы про
    # кожу, а призрак жил бы на фоне, где его никто не мерит. Ровно так этот
    # дефект и дожил до композита
    roi_open = open_bands[top:bottom, x0:x1]
    skin_inside = roi_open.copy()
    if skin_zone is not None:
        skin_inside &= skin_zone[top:bottom, x0:x1] > 0
    if above_jaw is not None:
        skin_inside &= above_jaw

    back_inside = (
        np.zeros_like(roi_open)
        if back_zone is None
        else roi_open & (back_zone[top:bottom, x0:x1] > 0)
    )
    if neck_hair is not None:
        back_inside = back_inside | (roi_open & neck_hair)
    inside = skin_inside | back_inside
    before = _structure(cv2.cvtColor(image[top:bottom, x0:x1], cv2.COLOR_BGR2GRAY), inside)
    after = _structure(cv2.cvtColor(np.rint(merged).astype(np.uint8), cv2.COLOR_BGR2GRAY), inside)

    result = image.copy()
    result[top:bottom, x0:x1] = np.rint(merged).astype(np.uint8)

    # Обещание «вне маски не тронуто» держится не на округлении арифметики
    untouched = mask == 0
    result[untouched] = image[untouched]

    meta = {
        "flattened": True,
        "wipe_ratio": wipe_ratio,
        "flat_ratio": flat_ratio,
        "sigma_px": round(sigma, 1),
        "sample_radius_px": radius,
        # Сколько пикселей кожи легло в каждую медиану. Ноль с одной стороны —
        # её лендмарки ушли за силуэт, и тон туда взят с противоположной щеки
        "sample_px": [left["px"], right["px"]],
        "tone_positive": [round(float(value), 1) for value in tone_positive],
        "tone_negative": [round(float(value), 1) for value in tone_negative],
        # Второй тон — фон по сторонам полосы. None означает, что вторая зона
        # выключена: разметки нет либо чистого фона в кадре не нашлось, и тогда
        # прядь над фоном снова остаётся размытым тёмным пятном
        "background_positive": (
            None if back_positive is None else [round(float(v), 1) for v in back_positive]
        ),
        "background_negative": (
            None if back_negative is None else [round(float(v), 1) for v in back_negative]
        ),
        "background_px": back_px,
        # Стороны схлопнулись разворотом: обе полосы залиты общим тоном
        "sides_collapsed": bool(collapsed),
        "band_px": int(np.count_nonzero(bands)),
        # Сколько из полосы дошло до маски — то есть где разрушение вообще
        # произошло. Заметно меньше band_px означает, что полосу съела защита
        "wiped_px": int(np.count_nonzero(open_bands)),
        # Сколько из разрушенного пришлось на персонажа, то есть где работала
        # заливка, а не одно размытие. Мало при большом wiped_px — полоса ушла
        # в сцену, и тоном кожи там ничего не залито (так и задумано)
        # Сколько залито каждым тоном. Ноль во втором при большом band_px — это
        # и есть та конфигурация, в которой возвращается низкочастотный призрак
        "filled_px": int(np.count_nonzero(inside)),
        "filled_skin_px": int(np.count_nonzero(skin_inside)),
        "filled_background_px": int(np.count_nonzero(back_inside)),
        # Сколько волос ниже челюсти удалось сжечь. Ноль на профильном кадре с
        # длинной причёской означает, что прорыв не сработал и хвост остался
        "filled_neck_hair_px": (
            0 if neck_hair is None else int(np.count_nonzero(roi_open & neck_hair))
        ),
        # Отсечена ли шея. False означает, что челюсть по сетке не построилась,
        # и заливка ушла ниже подбородка — там, где освещение другое
        "jaw_clipped": above_jaw is not None,
        # Структура под полосой до и после, уровни 0..255. Упало на порядок —
        # цепляться редактору не за что. Осталось прежним — сигма мала либо
        # полоса прошла мимо пряди, и это уже про cheek_ratio, а не про сигму
        "structure_before": round(before, 2),
        "structure_after": round(after, 2),
    }
    log.info("структура старой пряди разрушена в полосе щеки", extra=meta)
    return result, meta
