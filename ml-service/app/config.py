"""Конфигурация сервиса. Единственное место, читающее окружение."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_prefix="ML_",
        extra="ignore",
        protected_namespaces=(),
    )

    env: str = "development"
    host: str = "0.0.0.0"
    port: int = 8000
    log_level: str = "info"
    log_dir: Path = Path("./logs")
    log_file: str = "app.log"
    log_error_file: str = "error.log"
    # Политика ротации совпадает с Node: сутки или превышение размера,
    # хранится log_backup_count ротированных файлов сверх активного
    log_rotate_when: str = "midnight"
    log_file_max_mb: int = 20
    log_backup_count: int = 14
    # JSON в консоль (prod) или человекочитаемый формат (dev). В файл — всегда JSON.
    log_json: bool = False

    # --- Шаг 1: фото-аппликация локально (rembg + OpenCV + mediapipe) ---
    # Голова заказчика вырезается целиком, с причёской, и вклеивается в шаблон
    # преобразованием подобия. Подробности — в segmentation.py и collage.py.
    #
    # Модели rembg. Для фотографии — человеческая: она заметно аккуратнее ведёт
    # край волос. Для обложки — общая: нарисованный персонаж человеческой
    # модели не всегда знаком. Веса качаются при первом запуске (~176 МБ на
    # модель) в кэш rembg; поставьте оба значения одинаковыми, чтобы обойтись
    # одной загрузкой.
    seg_model_photo: str = "u2net_human_seg"
    seg_model_cover: str = "u2net"

    # Область головы — эллипс по сетке лица, в долях размеров лица. Силуэт от
    # сегментатора обрезается по ней: он знает, где кончаются волосы, но не
    # знает, где кончается голова.
    #
    # hair — сколько высот лица (подбородок → брови) отложить вверх от
    #   подбородка. 2.3 соответствует канону (до макушки — две) плюс запас на
    #   объём причёски. Мало — срежется верх причёски, много — в кадр полезет фон.
    head_hair_ratio: float = 2.3
    # neck — на сколько опустить срез НИЖЕ ЛИНИИ ЧЕЛЮСТИ (сама линия берётся из
    #   сетки, а не проводится прямой через подбородок). Ноль — режем ровно по
    #   челюсти: ни шея, ни воротник, ни одежда заказчика в аппликацию не
    #   попадают. Больше нуля — оставляем полосу шеи, если модели не хватает
    #   материала, чтобы дорисовать воротник.
    head_neck_ratio: float = 0.0
    # width — ширина эллипса в долях ширины лица. Запас на пышные причёски.
    head_width_ratio: float = 1.6
    # erode — на сколько подрезать край силуэта внутрь, доля высоты лица.
    #   Граница rembg идёт по внешним пикселям волос, а они наполовину состоят
    #   из фона фотографии: без подрезки этот фон переезжает на обложку грязной
    #   каймой вокруг причёски. 0.006 — это 2-3 px на типичном портрете. Много —
    #   объедаются тонкие пряди, ноль — возвращается ореол.
    head_erode_ratio: float = 0.006

    # feather — растушёвка края аппликации. Коллаж намеренно жёсткий: ровно
    #   столько, чтобы убрать ступеньку антиалиасинга по контуру волос.
    collage_feather_ratio: float = 0.01
    # colour_match — доля приведения тона КОЖИ к лицу шаблона (среднее и
    #   разброс по каналам LAB). Волос не касается: их цвет переносится ради
    #   того, чтобы он остался цветом заказчика. Геометрию не трогает, снимает
    #   разницу между светом фотостудии и светом иллюстрации — при strength 0.2
    #   модель сама свести освещение не успевает. 0 — цвет фотографии как есть.
    collage_colour_match: float = 0.8
    # Стирать ли голову нарисованного персонажа из-под вклейки. Без этого у
    # длинноволосого героя вокруг вклеенной головы остаётся его собственная
    # шевелюра. Выключать имеет смысл, только если сегментатор раз за разом
    # промахивается по конкретной серии обложек.
    collage_erase_template_head: bool = True
    # Чем затягивать место стёртой головы:
    #   pyramid — заливка пирамидой (push-pull). Не даёт ни штрихов, ни колец и
    #     на 4K в 13 раз быстрее Telea; на наших обложках отклонение от
    #     окружающего фона 2.9 из 255;
    #   telea, ns — cv2.inpaint. Сравнимы по чистоте (1.7 и 3.2), но стоят 20-27
    #     секунд на 4K: дыра здесь размером с голову.
    collage_erase_method: str = "pyramid"
    # Насколько прямой срез области стирания опускается ниже подбородка
    # персонажа, доля высоты лица. Запас на погрешность сетки — и только: ниже
    # лежит его шея, а на неё садится вклеенная голова (своей у неё нет, она
    # обрезана по челюсти). Сотрёшь — под подбородком останется дыра.
    collage_erase_neck_ratio: float = 0.05
    # Запас вокруг силуэта персонажа, доля высоты лица. Стирать впритык нельзя:
    # по краю рисованных волос идёт полупрозрачная кромка, и она остаётся
    # тёмной каймой ровно там, где её должно было не стать.
    collage_erase_pad_ratio: float = 0.03

    # --- Шаг 2: облачный инференс на fal.ai ---
    # Ключ читается fal-client из окружения как FAL_KEY — без префикса ML_,
    # поэтому дублируем сюда только для проверки готовности в /health/ready.
    fal_key_env: str = "FAL_KEY"
    fal_timeout_s: int = 600

    # Гиперпараметры второго шага сюда не переехали, и это осознанно: они
    # связаны между собой (strength, ширина градиента маски, веса ControlNet
    # подбираются вместе) и живут набором — профилем — в
    # app/pipelines/refine/profiles.py. Здесь только выбор профиля и точечные
    # переопределения для подбора на живом сервисе.
    #
    # seam — консервативный режим: strength 0.20, маска-плато по стыку.
    # blend — рабочий: strength 0.26, градиентная маска. Шея и контур волос
    #   сводятся мягко, но геометрия причёски не плывёт — выше ~0.28 она едет,
    #   и без карт ControlNet удержать её нечем.
    # stylise — strength 0.5, та же маска. Без карт рискует контуром причёски.
    # stylise_controlnet — то же плюс Canny и Depth; нужен эндпоинт, который их
    #   принимает, а на рабочем висит наша LoRA, и уходить с него незачем.
    refine_profile: str = "blend"

    # Пустое значение или None означает «взять из профиля». Именно поэтому
    # None, а не число: иначе не отличить «оператор поставил 0.2» от «оператор
    # не трогал».
    refine_strategy: str = ""
    refine_endpoint: str = ""
    refine_prompt: str = ""
    refine_strength: float | None = None
    refine_guidance_scale: float | None = None
    refine_steps: int | None = None
    # Ширина градиента маски, доля высоты лица. На высоком strength маска-плато
    # даёт видимую ступеньку по своей границе.
    refine_gradient_ratio: float | None = None
    # Какие карты ControlNet оставить: «canny,depth» или «none». Веса и пороги
    # остаются из профиля — подбирать их строкой в окружении означает получить
    # набор, который потом никто не воспроизведёт.
    refine_controls: str = ""

    # 4K-обложки занимают 25-30 МБ; значение продублировано в .env.example
    max_upload_mb: int = 40

    allowed_origins: str = "http://localhost:3000"

    @field_validator(
        "refine_strength",
        "refine_guidance_scale",
        "refine_steps",
        "refine_gradient_ratio",
        mode="before",
    )
    @classmethod
    def _blank_means_from_profile(cls, value: object) -> object:
        """
        Пустая строка — это «не задано», а не ноль.

        В .env.example переопределения профиля перечислены с пустыми значениями:
        так видно, что ручка есть. Без этого разбора pydantic честно попытается
        сделать из "" число и уронит сервис на старте — на конфиге, который
        оператор считает пустым.
        """
        return None if isinstance(value, str) and not value.strip() else value

    @property
    def origins(self) -> list[str]:
        return [o.strip() for o in self.allowed_origins.split(",") if o.strip()]

    @property
    def max_upload_bytes(self) -> int:
        return self.max_upload_mb * 1024 * 1024


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()
