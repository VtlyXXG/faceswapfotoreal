"""Конфигурация сервиса. Единственное место, читающее окружение."""

from __future__ import annotations

from functools import lru_cache
from pathlib import Path

from pydantic import field_validator
from pydantic_settings import BaseSettings, SettingsConfigDict


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=".env",
        env_prefix="ML_",
        extra="ignore",
        protected_namespaces=(),
    )

    env: str = "development"
    host: str = "0.0.0.0"
    port: int = 8000
    log_level: str = "info"
    log_dir: Path = Path("./logs")
    log_file: str = "app.log"
    log_error_file: str = "error.log"
    # Политика ротации совпадает с Node: сутки или превышение размера,
    # хранится log_backup_count ротированных файлов сверх активного
    log_rotate_when: str = "midnight"
    log_file_max_mb: int = 20
    log_backup_count: int = 14
    # JSON в консоль (prod) или человекочитаемый формат (dev). В файл — всегда JSON.
    log_json: bool = False

    # --- Шаг 1: маска головы НА ШАБЛОНЕ (локально, mediapipe + OpenCV) ---
    #
    # Единственная локальная работа, которая осталась. Голова заказчика больше
    # никуда не вырезается и никуда не вклеивается: с фотографии берётся только
    # личность, и уезжает она референсом. Локально нужно ответить на один
    # вопрос — какую область шаблона отдать модели на перерисовку.
    #
    # Семантическая разметка человека (mediapipe ImageSegmenter): лицо, волосы,
    # кожа тела, одежда. По ней и строится маска: класс «волосы» знает форму
    # причёски персонажа, а сетка лица про волосы не знает ничего.
    # Пусто — файл ищется в ~/.mediapipe (или $MEDIAPIPE_HOME). Без файла
    # маска строится эллипсом по сетке лица, см. head_mask.py.
    parsing_model: str = ""

    # Доли маски. Пусто или None — «взять из профиля»: маска и strength
    # подбираются вместе, и разъезжаться им нельзя. Числа здесь — для подбора на
    # живом сервисе, без пересборки образа.
    #
    # dilate — расширение маски за контур головы персонажа, доля высоты его
    #   лица. Ради него всё и делается: генерация внутри маски-впритык оставляет
    #   по краю контур чужой причёски.
    mask_dilate_ratio: float | None = None
    # feather — размытие краёв маски. Жёсткий край даёт видимую границу
    #   генерации ровно там, где проходит маска.
    mask_feather_ratio: float | None = None
    # neck — насколько маска опускается ниже подбородка персонажа. Там модель
    #   сводит новую голову с шеей и воротником; без запаса голова садится на
    #   чужую шею встык.
    mask_neck_ratio: float | None = None

    # --- Шаг 2: облачный инференс на fal.ai ---
    # Ключ читается fal-client из окружения как FAL_KEY — без префикса ML_,
    # поэтому дублируем сюда только для проверки готовности в /health/ready.
    fal_key_env: str = "FAL_KEY"
    fal_timeout_s: int = 600

    # Гиперпараметры генерации сюда не переехали, и это осознанно: они связаны
    # между собой (strength, доли маски, вес идентичности подбираются вместе) и
    # живут набором — профилем — в app/pipelines/refine/profiles.py. Здесь
    # только выбор профиля и точечные переопределения для подбора.
    #
    # pixar_real — фотореализм: кожа с текстурой, мягкие тени, 85 мм;
    # impasto    — живопись: густой мазок, фактура холста.
    refine_profile: str = "pixar_real"

    # Пустое значение или None означает «взять из профиля». Именно поэтому
    # None, а не число: иначе не отличить «оператор поставил 0.2» от «оператор
    # не трогал».
    refine_strategy: str = ""
    refine_endpoint: str = ""
    # Семейство схемы запроса: имена полей у эндпоинтов разные, и лишний ключ
    # fal не игнорирует, а заворачивает весь запрос. Список — payloads() в
    # profiles.py.
    refine_payload: str = ""
    refine_style: str = ""
    # Описание сцены — дополнение к промпту стиля. Пусто: работает один стиль.
    refine_scene: str = ""
    refine_strength: float | None = None
    refine_guidance_scale: float | None = None
    refine_steps: int | None = None
    # Имя поля, в котором эндпоинт ждёт референс личности, и вес этого
    # референса. Поле — часть профиля, а не константа кода: у kontext это
    # reference_image_url, у flux-general свои image_prompts.
    refine_identity_field: str = ""
    refine_identity_scale: float | None = None

    # --- Шаг причёски: первый вызов двухшаговой стратегии (hair_swap) ---
    #
    # Фейссвоп переносит лицо и только лицо: причёска остаётся от шаблона.
    # Двухшаговая стратегия правит её отдельным проходом ПЕРЕД заменой лица —
    # мультикартиночным редактором по шаблону и фотографии заказчика. Ручки
    # отдельные, потому что эндпоинт другой: ML_REFINE_ENDPOINT относится к
    # замене лица и на причёску не влияет.
    #
    # Включается это не здесь, а профилем: ML_REFINE_PROFILE=pixar_hair (или
    # ML_REFINE_STRATEGY=hair_swap). Числа ниже работают только у него.
    #
    # endpoint/payload — какой редактор и по какой схеме. Живых три:
    #   fal-ai/nano-banana/edit (умолчание, точнее держит остальной кадр),
    #   fal-ai/bytedance/seedream/v4/edit (единственный отдаёт 4K),
    #   fal-ai/hy-wu-edit (умеет думать перед правкой).
    # Схема — только «одиночная»: nano_banana_solo | seedream_solo | hy_wu_solo.
    # Обычные (nano_banana, seedream_edit) кладут в массив фотографию заказчика,
    # и редактор рисует по ней второе лицо — такой профиль не собирается вовсе.
    hair_endpoint: str = ""
    hair_payload: str = ""
    # Словами о причёске заказчика: «short blonde buzz cut». ЕДИНСТВЕННЫЙ
    # источник того, что рисовать на первом шаге, — фотография туда не уезжает.
    # Пусто — описание обязано прийти в поле hair запроса, иначе заказ
    # отклоняется до сети
    hair_description: str = ""
    # Геометрия маски волос, доли высоты лица персонажа. dilate — расширение за
    # контур причёски (там модель кладёт новую линию роста волос и затирает
    # ореол старой), feather — растушёвка края вклейки
    hair_dilate_ratio: float | None = None
    hair_feather_ratio: float | None = None
    # protect — поле защиты вокруг лица. Единственное число между диффузией и
    # глазами персонажа: под ним маска волос гаснет, и лицо доезжает до
    # фейссвопа нетронутым
    hair_protect_ratio: float | None = None
    # forehead — докуда маска спускается по лбу, в долях высоты лица НАД
    # бровями. 0 — до самых бровей: лоб целиком рисует редактор, полосы старой
    # кожи между лицом от фейссвопа и новой причёской не остаётся, а стык уходит
    # в брови, под растушёвку самого фейссвопа. 0.5 и больше — лоб не трогается
    # (умолчание). Крутить это, а не protect, когда над бровями виден рубец:
    # protect меняет ширину поля защиты, а не её форму, и лоб защищён классом
    # разметки при любом его значении
    hair_forehead_ratio: float | None = None
    # core — во сколько раз сжать ядро лица ПОПЕРЁК его оси. Ядро — выпуклая
    # оболочка глаз, носа и рта: единственное место, где защита сильнее волос.
    # 1.0 (умолчание) — как построено; 0.75 сильнее открывает виски и скулы,
    # где застревают пряди старой причёски. Углы глаз при сжатии остаются под
    # защитой: дилатация ядра круговая и возвращает накрытие наружу
    hair_core_ratio: float | None = None
    # guard — какую долю ПОЛУШИРИНЫ защиты лица оставить. 1.0 (умолчание) — всю.
    # Единственная ручка против пряди, которую разметка отнесла к классу лица:
    # в маску такая прядь не входит (для разметки она не волосы) и вычитается
    # вместе с защитой, а защита отнимается ПОСЛЕ дилатации — то есть расширять
    # маску за такой прядью бесполезно, на щеке она умножится на ноль. Меньше —
    # щёки и виски выходят из-под защиты целиком; ядро лица (глаза, нос, рот)
    # возвращается поверх среза и этой ручкой не открывается
    hair_guard_ratio: float | None = None
    # cheek — докуда спускается полоса вдоль щеки, доли высоты лица НИЖЕ
    # подбородка (0.35 — до воротника). 0 отключает полосу.
    #
    # Единственное, чем берётся локон, которого сегментатор не видит ВООБЩЕ: ни
    # волосами, ни лицом. Такая прядь недостижима ничем из чисел выше по
    # построению — dilate расширяет источник, которого нет, а guard и core
    # только отпускают защиту, области не добавляя. Полоса задаёт область
    # геометрией: два прямоугольника в осях головы, от виска вниз мимо челюсти к
    # воротнику, снаружи от внешних углов глаз. Разметку она не спрашивает вовсе
    # и защиту лица гасит наравне с настоящими волосами — иначе класс FACE
    # вычел бы её обратно.
    #
    # Глаза, нос и рот ею не открываются ни при каком значении: ядро лица
    # накладывается поверх. Платим щеками и шеей — они уходят под диффузию.
    # Смотреть в мете hair.cheek_px / cheek_hair_px / cheek_open_px: второе
    # почти ноль при большом первом — разметка волос там и правда не видит;
    # третье заметно меньше первого — полосу съела защита, и вот тогда guard
    hair_cheek_ratio: float | None = None
    # erase — насколько размыть заливку, которой старая причёска стирается в
    # кадре ДО отправки редактору. 0 (умолчание) — стирания нет.
    #
    # Провалившийся путь, оставленный переключателем. Гипотеза была в том, что
    # редактор цепляется за структуру старых волос внутри открытой маски; живой
    # прогон её опроверг и заодно доказал обратное: стирание залило мылом всю
    # область, а прядь на щеке осталась резкой — то есть лежала вне маски
    # целиком. Так и выяснилось, что разметка её не видит, и появился
    # ML_HAIR_CHEEK_RATIO. Цена выяснилась там же: без силуэта старой копны
    # редактор рисует ёжик прямо по черепу (голова выходит лысой), а границы
    # заливки возвращают тот самый светлый ореол вокруг головы
    hair_erase_ratio: float | None = None
    # crop — поле вокруг маски волос: редактору уезжает окно с головой, а не
    # разворот целиком. Первый прогон показал, зачем: на полном 4K причёска
    # занимает проценты кадра, и модель отдаёт мыльную шапку вместо стрижки.
    # 0 выключает окно и возвращает прежнее поведение
    hair_crop_ratio: float | None = None
    # Насколько правка обязана изменить кадр ВНУТРИ маски, уровни 0..255. Ниже —
    # редактор промолчал, вернув шаблон как есть, и заказ отклоняется
    hair_min_changed: float | None = None

    # Подготовка референса личности перед отправкой, см. pipelines/reference.py.
    # Портрет крупным планом задаёт генерации свой масштаб, и голова выходит
    # больше маски; вокруг фотографии кладётся поле, отдаляющее лицо до
    # масштаба персонажа на шаблоне. Ширина поля вычисляется по двум замерам,
    # здесь только границы.
    #
    # pad_max — предел роста холста; 1.0 выключает подготовку целиком
    reference_pad_max: float | None = None
    # pad_ratio — слепое поле, когда лица на фотографии не нашлось
    reference_pad_ratio: float | None = None

    # 4K-обложки занимают 25-30 МБ; значение продублировано в .env.example
    max_upload_mb: int = 40

    allowed_origins: str = "http://localhost:3000"

    @field_validator(
        "mask_dilate_ratio",
        "mask_feather_ratio",
        "mask_neck_ratio",
        "refine_strength",
        "refine_guidance_scale",
        "refine_steps",
        "refine_identity_scale",
        "hair_dilate_ratio",
        "hair_feather_ratio",
        "hair_protect_ratio",
        "hair_forehead_ratio",
        "hair_core_ratio",
        "hair_guard_ratio",
        "hair_cheek_ratio",
        "hair_erase_ratio",
        "hair_crop_ratio",
        "hair_min_changed",
        "reference_pad_max",
        "reference_pad_ratio",
        mode="before",
    )
    @classmethod
    def _blank_means_from_profile(cls, value: object) -> object:
        """
        Пустая строка — это «не задано», а не ноль.

        В .env.example переопределения профиля перечислены с пустыми значениями:
        так видно, что ручка есть. Без этого разбора pydantic честно попытается
        сделать из "" число и уронит сервис на старте — на конфиге, который
        оператор считает пустым.
        """
        return None if isinstance(value, str) and not value.strip() else value

    @property
    def origins(self) -> list[str]:
        return [o.strip() for o in self.allowed_origins.split(",") if o.strip()]

    @property
    def max_upload_bytes(self) -> int:
        return self.max_upload_mb * 1024 * 1024


@lru_cache
def get_settings() -> Settings:
    return Settings()


settings = get_settings()
