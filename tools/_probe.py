"""
Отдельный набор под новый материал: шаблон dino3 и доноры 67/68, мимо стенда.

ЗАЧЕМ ОТДЕЛЬНО, А НЕ СТРОЧКАМИ В `_bench`. Стендовые 21 кадр заморожены
намеренно: пары «кадр — донор» менять нельзя, иначе новые числа не сравнить со
старыми. Дописать к ним новые строки тоже нельзя без потерь — итоговая строка
каждой сводки (среднее сходство, сумма прядей, худший ракурс, среднее
отклонение светлоты) считается ПО ВСЕМУ НАБОРУ, и на 27 кадрах она перестанет
сходиться с записанной историей 21-кадровых прогонов. Поэтому здесь свой набор,
своя папка `storage/output/probe` и свои приставки; в стендовые таблицы эти
кадры не попадают никогда.

ЧТО ЗДЕСЬ НЕ ПОВТОРЯЕТСЯ. Ни одной мерки. Геометрия шаблона, пороги, полоса у
контура, счёт прядей — всё берётся из `_bench` как есть. В README к этим
инструментам записано, чем кончается расхождение мерок: пять скриптов рядом
считали одно и то же по-разному, и широкое окно вместо полосы дало ровные 772
«пряди» и до правки, и после, то есть не разделило комплекты вовсе. Второй
набор с собственной копией той же арифметики — тот же капкан, только с двумя
источниками правды вместо одного. Поэтому `activate()` ПОДМЕНЯЕТ словарь набора
в уже импортированном `_bench` и больше ничего не делает. Подмена живёт в своём
процессе: стендовые скрипты `_probe` не импортируют и видят прежние 3x7.

СОСТАВ — три шаблона на три личности, девять кадров:

    dino1, dino2  стендовые шаблоны, здесь как опора. Без них числа нечитаемы:
                  абсолютное значение сходства или резкости само по себе ни о
                  чём не говорит, а рядом с известным кадром видно, новый ли
                  донор просел или новый шаблон;
    dino3         новый (пришёл как «шаблон67.png», переименован — cv2.imread
                  на Windows не открывает пути с кириллицей и молча отдаёт
                  None). 1408x768, лицо персонажа 86 px = 11.2% высоты кадра,
                  поза yaw -0.66 / pitch -0.29: голова повёрнута и задрана
                  вверх. Выраженный ракурс тут в плюс — на нём `pose_shift`
                  сразу покажет, если генератор снова начнёт разворачивать
                  голову в фас, как было на прогоне с растянутым кадром;
    id67, id68    новые дети. Проверены вектором личности: косинус с каждой из
                  семи стендовых личностей не выше 0.18 при пороге «тот же
                  ребёнок» 0.30, между собой 0.198. donor67 — 236x353, лицо
                  79 px = 22.5% высоты кадра, это чуть ниже четверти, которую
                  просит `donors/README.txt`; самый слабый снимок в наборе, и
                  если его сходство просядет, смотреть надо сюда, а не в
                  пересадку. donor68 — 678x452, лицо 150 px = 33.1%;
    id4           стендовый донор6, контрольный. На dino1/dino2 с тем же зерном
                  даёт те же кадры, что и стендовый прогон, — якорь, по
                  которому видно, что комплект вообще посчитался как обычно.

Контрольные кадры dino1_id4 и dino2_id4 — единственная работа, которая здесь
дублируется. Если якорь не нужен, они пропускаются:

    python tools/probe_batch.py render --seed 1234 --prefix S1234_ \\
        --only dino3_id4 dino1_id67 dino1_id68 dino2_id67 dino2_id68 \\
               dino3_id67 dino3_id68
"""
from __future__ import annotations

import sys

import cv2

import _bench

# Значения стендовых записей берутся из `_bench` по ссылке, а не переписываются
# сюда: копия разъехалась бы при первой же правке пути, и набор молча поехал бы
# мерить не тот файл
TEMPLATES = {
    "dino1": _bench.TEMPLATES["dino1"],
    "dino2": _bench.TEMPLATES["dino2"],
    "dino3": "dino3.png",
}
DONORS = {
    "id67": "donors/donor67.jpg",
    "id68": "donors/donor68.jpg",
    "id4": _bench.DONORS["id4"],
}
STEMS = [f"{key}_{tag}" for key in TEMPLATES for tag in DONORS]

OUT = _bench.ROOT / "storage" / "output" / "probe"

# Модули мерок делают `from _bench import TEMPLATES, DONORS, OUT`, то есть
# забирают ссылку в момент импорта. Если такой модуль уже импортирован, подмена
# до него не доедет и набор молча посчитается стендовым — ровно тот сорт
# отказа, из-за которого здесь всё и написано
_LATE = ("render_batch", "measure_batch", "strand_count", "skin_level", "contact_sheets")


def _must_read(rel: str) -> None:
    """Файл на месте И открывается тем же imread, которым его возьмут мерки."""
    path = _bench.ROOT / rel
    if not path.exists():
        raise SystemExit(f"нет файла {path}")
    if cv2.imread(str(path)) is None:
        raise SystemExit(
            f"{path} лежит на месте, но cv2.imread вернул None. На Windows он не "
            f"открывает пути с не-ASCII символами — переименуйте файл латиницей."
        )


def activate() -> None:
    """
    Подменить стендовый набор своим. Вызывать ДО импорта модулей мерок.

    Меняются ровно четыре имени в `_bench`: состав набора и папка вывода. Сами
    мерки, пороги и геометрия не трогаются — в этом весь смысл затеи.
    """
    late = [name for name in _LATE if name in sys.modules]
    if late:
        raise SystemExit(
            f"поздно: {', '.join(late)} уже импортированы и держат ссылку на "
            f"стендовый набор. activate() должен идти до их импорта."
        )

    for rel in (*TEMPLATES.values(), *DONORS.values()):
        _must_read(rel)

    _bench.TEMPLATES = TEMPLATES
    _bench.DONORS = DONORS
    _bench.STEMS = STEMS
    _bench.OUT = OUT
    OUT.mkdir(parents=True, exist_ok=True)
